export function homeworkPrompt(ask, knowledge, { picked = false } = {}) {
  return HOMEWORK_PROMPT.replace('{{PICK}}', homeworkPickBlock(picked, ask)).replace('{{KNOWLEDGE}}', homeworkKnowledgeBlock(knowledge))
}

