/* 走 src/lib/http.js 而不是内置 fetch：
   fetch（undici）连本机 HTTPS 会挂住（实测），而这条链路以后很可能指向自建/本机代理。
   超时必须有：识别服务会排队，没超时的话前端一直转圈，用户以为是自己写错了。

   mode —— 'formula'（默认，认公式）| 'text'（认普通文字，白板的「美化手写」用）。
   ★ SimpleTex 走不通 text 模式：它的接口契约就是"一张图 → 一个 LaTeX"，
     没有"给我文字"这回事。**在这里挡掉、并且说清楚该换哪一家**，
     比让它认出一堆 `\text{...}` 再回来强 —— 那种失败用户根本看不懂。
     这个判断放在服务端而不是前端，是因为"哪家能干什么"是这一层的知识。 */
export async function callProvider(cfg, imageBytes, { mode = 'formula', timeoutMs = 30000, input = '', lines = '', page = 0, question = '', history = [], image2 = null, images = [], picked = false } = {}) {
  if (mode !== 'formula') {
    if (cfg.provider === 'simpletex') {
      const what =
        mode === 'board'
          ? '整板转录'
          : mode === 'structure'
            ? '结构整理'
            : mode === 'doc'
              ? '课件整理'
              : mode === 'docsum'
                ? '课件提纲'
                : mode === 'rules'
                  ? '做题须知'
                  : mode === 'ask'
                ? '框选追问'
                : mode === 'homework'
                  ? '作业辅导'
                  : mode === 'hwask'
                    ? '作业追问'
                    : mode === 'lookup'
                      ? '速查'
                      : '认普通文字'
      return {
        ok: false,
        kind: 'provider',
        error: `SimpleTex 只认公式，${what}要用 DeepSeek —— 去「手写识别设置」里把「用哪家识别」换成 DeepSeek，再点一次。`,
      }
    }
    return callDeepSeek(cfg, imageBytes, { mode, timeoutMs, input, lines, page, question, history, image2, images, picked })
  }
  return cfg.provider === 'simpletex'
    ? callSimpleTex(cfg, imageBytes, { timeoutMs })
    : callDeepSeek(cfg, imageBytes, { mode, timeoutMs })
}

/* 把 http 层的报错/状态码翻译成"用户该干什么"。
   两家服务共用这一套分类，因为下一步是同一批：改密钥 / 等额度 / 查网络。 */
function classifyHttp(status, text) {
  let body = null
  try {
    body = JSON.parse(text)
  } catch {
    /* 不是 JSON —— 只能按状态码说 */
  }
  const msg = body && body.error && (body.error.message || body.error.msg || body.error)
  if (status === 401 || status === 403) {
    return { ok: false, kind: 'key', error: '密钥不对或者没权限（去设置里重新填一次）', httpStatus: status, raw: text.slice(0, 300) }
  }
  if (status === 429) {
    return { ok: false, kind: 'quota', error: '额度用完了（或者请求太快被限流）', httpStatus: status, raw: text.slice(0, 300) }
  }
  return {
    ok: false,
    kind: 'bad',
    error: (msg ? String(msg) : `识别服务回了 HTTP ${status}`) + (status === 402 ? '（余额不足）' : ''),
    httpStatus: status,
    raw: text.slice(0, 300),
  }
}

/* ── 每一趟的**输出上限**（max_tokens）──────────────────────────────────────
 *
 * ★★ 实测（2026-09-22 的一次性探针，见 README「省钱那一节」）：**thinking 的 token
 *   也算在这个数里面**。`max_tokens=100` 的那一次，100 个 token 全被思维链吃掉 ——
 *   `content` 长度是 **0**、`finish_reason` 是 `length`。
 *   所以它**不是省钱开关**：设小了会把答案整个掐掉，而前端只会看到"模型没回内容"
 *   （`kind:'empty'`）→ 判成"这一页没读出来"→ 重读一遍，既慢又更贵。
 *   想省钱只有两条路：关 thinking、或者降 effort（`reasoning_effort`）。
 *
 * 它唯一的用处是**给跑飞兜底**：不设的话上限是 384K token —— 一次调用最贵能到 $0.46
 * （384K × 输出价 $1.2/M）。下面的数按实测留了三四倍余量：同一页 thinking 900~3200
 * token、正文 500~800 token，所以"一页"给 8000 —— 正常的回话永远碰不到这条线。
 *
 * ⚠ 加一趟新的 mode 就回这儿加一行。**只有这一处**说"每趟最多回多少"。
 */
export const MODE_LIMITS = {
  /* 认公式：回的是一行 LaTeX，但 thinking 照样可能很长（它就是"看图想"） */
  formula: 4000,
  /* 美化手写：一段文字，可能几十行 */
  text: 4000,
  /* 整板转录：一整块板的内容，行最多的一趟 */
  board: 16000,
  /* 结构整理：纯文本 JSON，行号一大堆 */
  structure: 8000,
  /* 课件整理：一页的 讲解 + 重点 + 公式 */
  doc: 8000,
  /* 框选追问：一段 120~300 字的回答 */
  ask: 6000,
  /* 作业辅导：一次几道题，每题一份答案 + 解析 */
  homework: 16000,
  /* 作业追问：一段 120~300 字的回答（和框选追问一个量级，但它可能贴出长式子） */
  hwask: 8000,
  /* 整份课件的提纲：六段 JSON，段段都是短句（**纯文本、不发图**）——
     和结构整理一个量级。★ 它是"第二趟"，钱几乎只花在输入上（那份摘要）。 */
  docsum: 8000,
  /* 做题须知：三段短句（比提纲还短 —— 一张读不完的须知等于没有须知）。
     ★ 它和 docsum **共用同一份摘要输入**，所以这趟的钱也只有输出那一侧。 */
  rules: 4000,
  /* 速查（2026-09-28）：上课突然不懂的那个词。
     ★★ 这一格的判据不是"答得全不全"，是**"等不等得起"** ——
     一个人站着等答案的时间是三五秒，超了他就跟丢老师讲的下一句了，
     那时候再全的解释也白搭。1500 够"一句解释 + 一个例子 + 两个相关词"
     （实测输出 400~700 token），剩下的余量只是保险。
     ⚠ 别因为"怕它答不完"往上加：多出来的额度不是在补安全，是在**勾它写长篇**，
       而长篇正是这个场景里最没用的东西（他要的是读一句就能接着听课）。 */
  lookup: 1500,
}

/* ── 每一趟**想多深**（reasoning_effort）──────────────────────────────────────
 *
 * ★★ 为什么有这张表（2026-09-23）：脑子里的默认一直是"thinking 开着、effort = high"
 *   （用户 2026-09-22 定的，理由是"先想一想本身有价值"）。那句话对**要讲明白**的那几趟
 *   是对的 —— 但它被套到了所有趟上，包括**只是照抄**的那几趟。而实测（README「出网
 *   这一趟的账」）：thinking 占一次调用输出的 **69%~89%**，按最贵的输出档计价。
 *   ⇒ "抄"的那些趟为一段用不上的思维链付了七成到九成的钱。
 *
 * ★★ 实测（2026-09-23，同一张课件页、同一句 DOC_PROMPT，只改这一档）：
 *
 *   | 档 | 用时 | 输出 token | 其中思维链 | 讲解长度 |
 *   | --- | --- | --- | --- | --- |
 *   | `high` | 8.5 s | 1793 | 1195（67%） | 1150 字 |
 *   | `low`  | 8.3 s | 1778 | 1143（64%） | 1273 字 |
 *   | **`off`** | **2.8 s** | **587** | **0** | 1232 字 |
 *
 *   两件事推翻了原先的直觉，做决定前先看这两条：
 *   ① **`reasoning_effort: 'low'` 基本没用** —— 只省了 15 个 token、时间没变。
 *      想省钱靠它是指望不上的，只有"整个关掉"这一刀有用。
 *   ② **关掉之后讲解并没有变差** —— 那份 1232 字比 high 那份还长，式子写得更全
 *      （"转述"这一趟要的东西本来就在图上，思维链是多余的）。
 *   ⇒ 所以这张表里**没有 `low`**：要么照抄（`'off'`），要么真要想（`high`），
 *      中间那一档是不存在的。
 *
 * ★ 分档的判据只有一条：**这一趟要不要"想"，还是只要"照抄"**。
 *   · `'off'` = 整个关掉（`thinking: { type: 'disabled' }`），图上是啥就写啥；
 *   · `high` = 要讲明白 / 要组织 / 要推理（追问、作业、提纲、须知、结构整理）。
 *
 * ⚠⚠ `'off'` 有一副作用，用之前必须知道：**关掉 thinking 之后 `temperature` 就生效了**
 *   （"thinking 模式下 temperature 被上游忽略"这件事只在开着的时候成立）。
 *   于是上面那个"识别用 0、讲人话用 0.3"的分岔**会突然开始起作用** ——
 *   给"讲人话"那几趟关 thinking 而不动 temperature，等于把它一把按成教科书腔，
 *   那正是用户抱怨过的"读完还是不懂"。所以 `'off'` 只该用在**抄写类**（那些趟本来就要 0）。
 *
 * ⚠ 这条**不是省钱开关的另一种写法**：`max_tokens` 设小了会把答案掐掉（见上一段），
 *   而降 effort 是让模型**少想一会儿**，答案照样完整 —— 两者不是一回事。
 * ⚠ 动了这张表里的任何一格，都要去 `usage` 那一行看一眼"省了多少、内容有没有变差"
 *   —— 那一行就是为了这一刻才存在的。
 * ⚠ 加一趟新的 mode 就回这儿加一行。**只有这一处**说"每趟想多深"。
 */
