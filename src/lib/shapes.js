/* ─────────────────────────── 阈值（都往保守那侧调）───────────────────────────
 *
 * 这些数是拿"手画的形状"和"汉字/乱涂"两边的直觉定的，每一条在 [6x] 里都有反证。
 * ★ 改任何一个之前，先想清楚"放松它会让什么**真实的手写内容**被误判成形状"。
 */

/* 判一条笔迹"够不够长"。太短的东西（一个点、一勾）没有形状可言。
   世界坐标像素。下面很多判据要先过这一关，不然一小段噪声的相对误差可以任意大。 */
export const MIN_DIAG = 26

/* ★★ 一笔至少要**这么多点**才谈得上"是个形状"。这一条是拿用户的真板量出来的。
 *
 * ⚠⚠ 为什么非要它（这是本轮踩出来的第二个大坑）：光看"够不够长"根本不够。
 *   真板上有大量 **12~19 个点、20~30px 见方**的碎笔迹（汉字的一小段、抬笔的残留），
 *   它们**全都**能通过 MIN_DIAG。而点一少，几何拟合就变得**毫无约束**：
 *   12 个点去贴一个三角形（3 个顶点 = 6 个自由度）几乎必然完美贴合
 *   —— 实测一大批这样的碎笔迹拿到 **score = 1.000**，看下来是**一堆散点**，
 *   连"一笔"都不算，更不要说圆或三角形。
 *
 * ★ 光靠"分数高就信"在这里是失效的：分高的原因不是"像"，而是"点太少"。
 *   所以判读之前先把这一关立起来。24 这个数：真人画一个圆/矩形
 *   （哪怕只有 30px 见方的小圆）也在 **30 个点以上**（手写采样很密），
 *   而汉字碎笔迹大多在 10~20 个点。中间留了一倍的余量。
 * ⚠ 它和 MIN_DIAG 是**两道独立的闸**，缺一不可：
 *   MIN_DIAG 管"画得够不够大"，这一条管"采样够不够密"。
 *
 * ★★ **它只管闭合的形状（圆/椭圆/矩形/三角形），不管直线。**
 *   直线那一侧用 `LINE_MIN_PTS`，理由写在 `recognizeShape` 上面那一段 ——
 *   一句话：抽稀之后一条直线的点数是"手抖了几个波峰"，本来就只有几个，
 *   拿 24 去卡它，等于让直线永远认不出来（真板 122 笔直线候选 100% 被它挡掉）。 */
export const MIN_PTS = 24

/* ★ 直线至少要几个点。**这一条和 MIN_PTS 不是一回事，别合并。**
 *
 * 直线判据只用到两个量：`sag`（离弦最远 / 弦长）、`netTurn`（净转角）。
 * 它们需要的最小结构是"首尾两点 + 至少一个中间点"—— 3 点。
 * ⚠ 2 点也能算 sag（恒为 0）和 turn（恒为 0），但那是**没有约束**的完美：
 *   任何一条两点笔迹都会拿到满分，包括"用户随手点了一下又抬笔"。
 *   3 点正好把这种退化挡掉，同时不向"手抖留下几个点"要任何东西。
 *
 * ★ 为什么不做成"点越多越可信"的连续量：抽稀已经把采样密度抹掉了
 *   （见 recognizeShape 那段实测），拿它当判据是在读一个已经不存在的信号。 */
export const LINE_MIN_PTS = 3

/* ★★ 直线要**够长**才认 —— 单位是**世界像素**，量的是首尾两点的**直线距离**（弦长）。
 *
 * 这一条是替"点数闸"的位置：直线认不出来这件事，真正的难点从来不是"点太少"
 * （点少是正常的、正确的），而是**"汉字的横"和"用户画的直线"在几何上是同一个东西**。
 * 两者都直、都不闭合、都可能只有 3~6 个点。
 *
 * ★ 分开它们的**只有尺度**。实测（用户 10 张真板，6362 笔）：
 *   "几何上就是直线"的笔有 322 笔，弦长分布 ——
 *     中位 37px、75% 分位 51px、90% 分位 82px、最大 527px。
 *   那些短的（37px 上下）就是汉字的一横、一笔竖撇；
 *   而**有意识画一条直线**是个明确动作，屏幕上通常要横跨半屏，
 *   世界坐标下 150px 起步（本机 k=2 时屏幕 300px）。
 *
 * ★ 取 110 的标定：
 *   · 真板上那 322 笔里弦长 > 110 的只有 **20 笔**（6%），
 *     也就是这一条几乎不放过汉字；
 *   · 自检 [7] 画的那条直线弦长 168（屏幕 336px），**轻松通过**；
 *   · 圆规那一族的最低要求 MIN_DIAG = 26 是"有没有形状可言"的底线，
 *     而直线这条是"**这是不是一个刻意画的图形**"，本来就该高得多。
 * ⚠ 太小（比如贴着 MIN_DIAG 取 26）：汉字的一横会被认成直线，
 *   而用户框住一整段笔记点「◯ 规整」时，那些字会被一条条拉直 —— 那是侵入。
 * ⚠ 太大（比如 200）：真用户画一条短直线（横穿一小块区域）就认不出来了。
 *   110 留了 4 倍于"汉字横中位数"的余量，也对得起"画一条线"这个动作的尺度。
 * ★ 它必须配反证：一条 [7] 那样的直线要能过（自检里钉着），
 *   而真板上那些汉字横要过不去（[6x] 那一节按真板量）。 */
export const LINE_MIN_CHORD = 110

/* ★★ `netTurn` 里那一步至少要跨出**对角线的一个比例** —— 方向采样能不能算数的底线。
 *
 * 为什么是"比例"而不是"多少个点"、也不是"多少像素"（三种我都试过，记下来）：
 *   · **多少个点**（原写法 `floor(n/8)`）：在 n < 16 时恒等于 1 ⇒ 退回逐点算方向。
 *     而判读吃的是**抽稀之后**的点，一条真手画的直线抽稀后只剩 4~15 个点
 *     （实测，和采样密度无关）—— 恰好落在退化区间里。
 *   · **多少像素**（我第二版写的 `MIN_DIR_STEP_PX = 6`）：看起来对，
 *     但相邻点间距本来就有 8~20px（实测量级）⇒ 一步就满足了 ⇒ **等于没写**
 *     （实测 k 报"1 → 1"，一个点都没多跨）。
 *   · ★ **对角线的一个比例**：这是唯一对"大图形/小图形"都成立的口径 ——
 *     方向噪声正比于 `抖动 / 跨距`，而"跨距该多大"取决于**这一笔有多大**
 *     （同一支笔、同一个手，画大圆和画小圆的相对抖动是一样的）。
 *
 * 标定：0.10 × 对角线。
 *   · 一条 168px 的直线 ⇒ 一步约 17px。实测相邻间距 9~20px ⇒ k 会从 1 抬到 2，
 *     把方向噪声从 ±12° 压到 ±6° 量级。
 *   · 一个半径 80 的圆（对角线 226）⇒ 一步约 23px，一圈约 22 步 ——
 *     仍然远多于"约 8 段"的目标，**不会**把圆数成几段折线。
 * ⚠ 太大（比如 0.25）会把圆压成"五六步"，净转角就数不出 360° 了；
 *   太小（≤ 0.05）在"点数少"时抬不起 k。 */
export const MIN_DIR_STEP_RATIO = 0.10

/* ★★★ `MIN_PT_DENSITY`（采样密度下限 = 点数 / 对角线）**删掉了**（2026-09-19）。
 *
 * 用户报「我画的比较大的时候会识别不出来」，拿他的真板量出来根因就是它。
 * 它原来的注释写着"挡住'一笔画得很大、但点稀得没法判断形状'" —— 方向是对的，
 * 但**这个比值做不到那件事**：分子（点数）几乎与尺寸无关（采点按屏幕距离、
 * 抽稀按绝对像素容差），分母（对角线）线性增长 ⇒ 图形越大比值越小。
 * 它测的不是"信息够不够"，而是"你画得够不够小"。
 *
 * 实测（用户真板 24 笔）：认出来的小笔密度 0.11~0.23、认不出来的大笔 0.07~0.13；
 * 而**点间距**随尺寸同步变大（小笔 6~16px、大笔 13~24px）—— "稀"是采样的属性。
 * 去掉它：用户板上 0 → 5 笔认出来，而六类反证（汉字折笔/一撇/C 形弧/乱涂/两种碎笔迹）
 * **一个都没被误认**（各形状的 score 闸挡住了）。
 *
 * ⚠ 想"调小一点再加回来"是**同一个错误**：问题不是阈值大小，是这个比值本身
 *   （分子分母随尺寸的变化率不同）—— 调小只是把临界尺寸挪远，画得更大照样掉出去。
 * ⚠ "点够不够多"这件事现在**只由 `MIN_PTS` 负责**，而它和尺寸无关。别把它一起删了。
 */

/* ★ 端点"离得不远"的容差：首尾两点的距离 / 笔迹对角线长度。
 *
 * ★★ 它不是闭合判据，只是**很松的预筛**。真正的判据是下面的 netTurn（净转角）。
 *    这一点必须说清楚，因为我第一版把它当成了硬判据，结果：
 *    真人画圆到起点时**常常多绕一小截**（这是画得准的表现），
 *    多绕 36° 之后末点已经沿圆周往前走了小半圈，首尾的**直线距离**自然变大 ——
 *    实测 1.15 圈时到 0.303、1.20 圈时到 0.420，而那一笔的净转角是 355°/365°，
 *    明明是"绕满一整圈"的铁证，却卡在 0.22 这个数字上被整笔判成"开口"。
 *
 * ★ 那为什么**不能只看净转角、把这一条删掉**？
 *    因为一条"来回划了好几趟"的线净转角也能很大（去 180° 回 180°，正负相消后是 0，
 *    但一趟去一趟回如果方向不完全相反，净转角会累积）——
 *    而且一条绕了两圈又停回原处的线，净转角 720°，它确实是"闭合"的。
 *    真正要挡的是"首尾根本不在一个地方"的那种（画到一半停下的弧、写到一半的字）：
 *    这类东西首尾的直线距离是**整个笔迹量级**的，所以一条很松的 0.45 就够挡住。
 *
 * 0.45 的标定：实测 1.20 圈的圆是 0.420（要放进来），
 *   而"C 形开口弧"（净转 170°）是 0.86、一个半圆是 1.0 —— 两者中间有大片空档。
 * ⚠ 调大它会放进"绕了一大圈但停在别处"的笔迹；调小它会挡掉正常的多绕收笔。 */
export const CLOSE_RATIO = 0.45

/* ★ 净转角到多少才算"绕回来合上了"（度）。
   一个圈 ≈ 360°；一条来回划的线 ≈ 0°；写字里的撇折一般 30°~120°。
   ★ 取 150° 而不是贴着 360 取 240：
     这两类的**间隔非常大**（"绕一圈"和"来回划"之间是 360 vs 0），
     所以门槛放在中间偏上的位置最稳 —— 不拘泥于"必须接近 360"。
     为什么要往下放：一个矩形**不是平滑的圈**，粗步长采样时四个直角会被抹平，
     实测净转角只报 187°（阈值 240 就把矩形判成"开口"，后面全错）。
     150° 离"写字拐弯"那一档（实测最高 119°）仍有足够余量。
   代价：一个**开口很大**的 C 形弧净转能到 170°，会被当成"闭合" ——
   但那没关系，因为"闭不闭合"只是**第一道筛**，认成圆还要过径向误差那一关，
   而 C 形弧的径向误差很大（缺了那一段必然是离群点）→ 照样认不出来。

   ⚠⚠ **它有一个盲区，必须知道**：netTurn 数的是"一共转过去多少"，
     所以它**往上是无界的** —— 一个绕了两圈的圆净转 620°，一个绕 1.2 圈的圆 368°。
     于是"绕了好几圈的笔迹"和"正常多绕一点收笔"在它眼里**没有区别**，都在 300~650 之间。
     → 没有任何阈值能同时做到"放进 1.2 圈、挡住 2 圈"。
     实测（`closureRatio` / 结果）：
       1.10 圈 closure 0.201 / 认成圆；1.15 圈 0.325 / 拒；1.20 圈 0.398 / 拒；
       1.50 圈 0.693 / 拒；**2.00 圈 0.013 / 认成圆** ← 末点转回起点旁边，closure 掉回 0
     这一类（多绕到接近整圈数）目前**靠 CLOSE_RATIO 那道松预筛挡着**，不靠这一条。
     要真正分开它们得另外引入一个"量到绕了几圈"的判据（比如 pathLen / 一个圆的周长），
     那需要先有圆的拟合结果，而"是不是圆"恰恰是我们要判的 —— 是个循环。
     ⇒ 现在的取舍：**多绕超过约 1.2 圈就不认**（认不出来，按钮不出现）。
       这比"认错"好；而且真要多绕那么多圈的人，本意也不是画一个圆。 */
export const NET_TURN_CLOSED = 150

/* ★ 直线：最大偏离 / 弦长。
   0.055 = 一条 200px 的线最弯处离弦 11px —— 相当直了。
   真人画直线的手抖通常在 2~4%，写字里那些"横"也在这个量级，
   所以**单靠这一条不足以区分"直线"和"一横"** —— 还得配下面的转角判据。
   （这是 ADR-0001 最直接的教训：直度中位 0.28 的东西被判成了箭头。） */
export const LINE_MAX_SAG = 0.055

/* ★ 直线：沿路径的**净**转角（度）—— 方向总共转过去多少，不是"转了多少次"。
 *
 * ⚠⚠ 这里我犯过一个很贵的错，记下来：一开始用的是 totalTurn（**绝对值之和**），
 *   结果一条**笔直的线**报出 76°~292° 的"累计转角"，全部被判死。
 *   原因：手写采样每一点都有抖动，12 个方向段每一步都抖 ±5°，
 *   取绝对值再累加，这些**方向随机、本该互相抵消**的抖动全变成了正数加起来。
 *   方向抖动是**零均值**的，所以正确的问题是"净转过去多少"（正负相消），
 *   不是"一共抖了多少下"。净转角对手抖不敏感，但对"真的拐了个弯"极其敏感：
 *   一条 L 形净转 90°，一个圆弧净转就是它的圆心角 —— 正是我们要的量。
 *
 * 24° 的标定：手画直线的净转角实测 1°~8°（抖动的残余）；
 *   一条"看起来像直线、其实是浅弧"的线净转 15°~30°；
 *   一个 C 形开口弧净转 100°+；L 形折笔净转 90°。 */
export const LINE_MAX_TURN = 24

/* ★★ 直线：**有符号弓形面积 / 弦长²** 的绝对值上限 —— 这是直线的真正判据。
 *
 * 为什么在 `sag` 和 `netTurn` 之外还要一条：那两条各有一个洞（详细的账写在
 * `fitLine` 里）。一句话 —— `sag` 拿"最远处"当代表，一条**对称的弧**最远处在中点、
 * `sag` 反而小；`netTurn` 在"点被抽稀到十几个"时退化成逐点噪声。
 * 面积按"点在弦的哪一侧"累积：手抖零均值（正负相消）、弧是单侧（累加）。
 *
 * 标定（全实测）：
 *   合成手画直线（16 点，抖幅 ±0.3~±2.5px）：|面积| = 0.0009 ~ 0.011
 *   真板弦 ≥ 110 里最"直"的几笔：              |面积| = 0.0012 ~ 0.0037
 *   真板上明显是弧的（sag ≥ 0.15）：            |面积| = 0.07 ~ 0.99
 *   ⇒ 取 0.03：比最抖的直线大一倍半、比最平的弧小一半，两边都有近一个数量级的余量。 */
export const LINE_MAX_AREA = 0.03

/* ★ 直线的分数按**实测典型值**归一，不按闸值 —— 理由见 fitLine 里那段
 *   （"用及格线当满分线"的错）。这两个数就是实测出来的典型值：
 *   · 0.011 = 抖到 ±2.5px 的直线（"抖得比较厉害但仍然明显是直线"）的面积；
 *   · 18°   = 手画直线净转角的上沿（实测 0.7°~17.5°）。
 *   ⚠ 改 `LINE_MAX_AREA` / `LINE_MAX_TURN` 时**不用**动这两个
 *     —— 它们的含义是"典型值"，和"闸"是两件事（这正是这一段要分开的东西）。 */
export const LINE_TYPICAL_AREA = 0.011
export const LINE_TYPICAL_TURN = 18

/* 多边形的"角"的判据：顶点处两侧方向的夹角（外角）至少要这么大才算一个真拐角，
   比这小的当成手抖（不造就近顶点）。 */
export const CORNER_MIN_TURN = 26 // 度

/* ★ 分段判"这里是不是一个角"的方向容差（度）。
 *   24° = 一条边走偏了 24° 才承认拐了 —— 手画直线的来回抖通常 3°~8°，
 *   所以不会把直边劈开；而直角是 90°、三角形的角 40°~120°，都远超它。
 *   ⚠ 调小会让手抖被数成角（矩形被切成五个六个角）；
 *     调大会让"画得很平的角"被漏掉（三角形算成一条折线）。 */
export const SEG_TOL_DEG = 24

/* 一段至少要有几个点才算一段（防"在同一个点附近切好几刀"）。 */
export const MIN_SEG_PTS = 3

/* 分段时最多允许几段。
   我们要认的是直线 / 三角 / 矩形 / 圆；一个手画图形需要超过 6 段折线才贴得住，
   它就不是我们想认的东西 —— 这个上限本身就是一道"宁可认不出来"的闸。 */
export const MAX_SEG = 6

/* ★ 每多分一段要付的"复杂度代价"（占对角线的比例）。
   多一段必然让误差变小（多一个自由度），不罚就会永远选段数最多的那版 ——
   那是过拟合，"圆"会被切成 6 段折线。1.5% 的标定：
   切一段**真边**带来的误差下降远超它（矩形从 2 段到 4 段，误差掉几十个百分点）；
   切**一段噪声**带来的下降几乎为零 → 被这一项罚掉。 */
export const CORNER_PENALTY = 0.015

/* ★ 分段重建的**可用**门槛：全局最坏偏离 / 对角线 超过它就认为"这几段贴不住这一笔"。
   0.06 = 一根 300px 的笔迹，最坏的地方离弦 18px。
   ⚠ 这是"数角"这一路的总闸：一个圆用 4 段折线去贴，误差一定远超它 → 圆不会被数成四边形。 */
export const FIT_WORST_MAX = 0.06

/* ★ 笔迹的**绝对噪声底**（世界像素）：采样抖动带来的、与图形大小无关的那部分误差。
 *   它必须先扣掉再谈"圆不圆"，否则小图形永远吃亏
 *   （半径 40 的圆上 4px 的抖动就是 10%，而它其实是笔画本来的抖，不是"画歪了"）。
 *   3.5 是拿手写采样在 1x 缩放下的实测抖动定的（量级和 ink.js 的 MIN_STEP_SCREEN 一致）。 */
export const NOISE_FLOOR = 3.5

/* 圆/椭圆：点到"拟合出来的那个圆/椭圆"的距离 / 半径，**中位数和高分位（92%）**都要过。
   ★ 用两个统计量是故意的：中位数管"整体圆不圆"，高分位管"有没有一段整体跑偏"
     （一个 C 形 + 一小段直边，中位数可能很好看）。
   ⚠ 第二道用 92 分位而不是最大值：收笔多绕一小段（很常见、而且说明画得准）
     不该被当成"不圆"，见 fitCircle 里那段注释。
   0.18 / 0.30 = 半径的 18% / 30%。真人画圆的偏差典型 5%~12%。 */
export const CIRCLE_MED_ERR = 0.18
export const CIRCLE_MAX_ERR = 0.30

/* 椭圆的两个半轴之比至少差这么多才算"椭圆"而不是"圆"（1 = 正圆）。
   低于这个比值的一律按圆拟合 —— 圆少一个自由度，结果更稳。 */
export const ELLIPSE_MIN_RATIO = 1.22

/* ★ 求圆心前把点**平滑**掉的那道窗宽（点数）。
   采样噪声 ~4px，几个点的滑动平均就能压掉；窗宽太大会把"手画的椭圆"也压圆。 */
export const SMOOTH_WIN = 5

/* ★ 按弧长等距重采样的点数。
   手写一笔两百多点，而这个数只服侍"求质心"这一件事 ——
   72 个等距点已经让质心的误差远小于噪声，再多只是白算。 */
export const RESAMPLE_N = 72

/* ★ 形状"有多像"的下限：低于它一律当**认不出来**。
   它是最后一道闸，也是上面那条铁律的执行者。 */
export const MIN_SCORE = 0.62

// ─────────────────────────────── 基本量 ───────────────────────────────

const DEG = 180 / Math.PI
const dist = (a, b) => Math.hypot(a.x - b.x, a.y - b.y)

/** 这一笔的端点距离 / 对角线长度（0 = 完全闭合，1 = 首尾离得和整个笔迹一样远）。
 *
 * ⚠ 它**只描述"首尾离得近不近"**，不等于"这一笔闭合了"。两个反例：
 *   ① 真人画圈最常见的收笔是**末点叠过起点一段**（手画圆到起点时常常多走一点点），
 *      那时端点距离能到对角线的 0.3~0.42，**画得越准反而越大**；
 *   ② 一条"来回划"的线首尾可能正好落在一起，它闭合得很"好"，但它不是个圈。
 *   所以它是 isClosed 里的**松预筛**，真正的判据是净转角（见 isClosed / netTurn）。 */
function closureRatio(pts) {
  const diag = diagOf(pts)
  if (!diag) return 1
  return dist(pts[0], pts[pts.length - 1]) / diag
}

/* 这一笔的**净转角**（度）：方向沿路径总共转了多少（带符号累加后再取绝对值）。
 *
 * ★ 为什么需要它：闭合有两种，而它们是**几何上不同的两类** ——
 *   · 一个绕回来的圈：净转角 ≈ ±360°（绕了一圈，中间那些来回抖抵消掉了）；
 *   · 一个来回划的线 / 一条折线 / 一个写字里的撇折：净转角 ≈ 0°。
 *   端点距离分不开这两类（都可能首尾靠近），净转角分得**干干净净**。
 *
 * ⚠ 方向采样要**足够粗**才能在噪声里有意义（这一步栽过两次）：
 *   逐点算方向 = 纯噪声；跨 2~4 个点算 = 还是噪声；
 *   跨 k 个点、k 至少 `MIN_DIR_STEP`（点数的小比例 + 一个绝对下限）才行。
 *   噪声是**零均值**的，所以净转角不像"绝对值之和"那样把噪声累加成大数 ——
 *   但残余仍和**步数**成正比，步子太碎残余就爬上来了
 *   （实测：一条笔直的线跨 n/24 步算，净转角报 37°；跨 n/8 步算就只剩几度）。
 *   所以步数刻意取得**少**（整条笔迹大约 8 个方向段）。
 *
 * ⚠⚠ **但"n/8"这一个条件在"点很少"的时候会失效**（2026-09-19 查出来的，
 *   代价是"直线一直认不出来"）：
 *   `floor(n/8)` 在 n < 16 时恒等于 1 —— 也就是**退回逐点算方向、纯噪声**。
 *   而判读吃的是**抽稀之后**的点（`simplifyPoints(pts, 0.6)`，见 recognizeShape），
 *   一条真手画的直线抽稀后正好就是 4~15 个点（实测，和采样密度无关）——
 *   于是**恰好落在这一步长退化的区间里**。
 *   实测一条完美笔直的线（15 点）：逐步转角是
 *     `10.0 -10.9 13.9 -14.7 14.4 -10.8 9.2 -12.6 14.7 -14.9 13.7 -11.2 10.1`
 *   —— 正负交替、绝对值 10~15°，正是"逐点噪声"的指纹。净转角因此多出 10.88°，
 *   把直线的分数从 0.878 压到 **0.547**（闸 0.62）→ **认不出来**。
 *   ⇒ 所以下面除了"点数比例"，还要有**一个按弧长的绝对下限**：
 *     这一步至少要跨出 `MIN_DIR_STEP_PX` 那么长的路，方向才有意义 ——
 *     这个量在噪声里会真的变大，在"点被抽稀了"之后依然成立
 *     （点数能被抽稀掉，弧长不能）。 */
function netTurn(pts) {
  const n = pts.length
  if (n < 3) return 0
  /* ★ 步长：点数比例（整条约 8 段）和**对角线比例**（抗噪声的下限）取较大的那个。
   *   两条各管一边：前者管"步数别太多"（整条笔迹约 8 个方向段），
   *   后者管"点数少时别退化成逐点"（见 MIN_DIR_STEP_RATIO 的注释，三种口径都试过）。 */
  let k = Math.max(1, Math.floor(n / 8))
  const stepFloor = diagOf(pts) * MIN_DIR_STEP_RATIO
  /* ⚠ 量"跨 k 个点走出去了多远"取**中间那一段**：首尾可能压着收笔/起笔的堆点，
   *   量出来偏小（我第一版写"累计弧长"就更糟 —— 相邻点间距本来就有 8~20px，
   *   一步就满足，k 一个都不加，等于没写）。 */
  while (k < n - 1) {
    const from = Math.max(0, Math.floor(n / 2) - Math.floor(k / 2))
    const to = Math.min(n - 1, from + k)
    if (dist(pts[from], pts[to]) >= stepFloor) break
    k++
  }
  let sum = 0
  let prev = null
  for (let i = 0; i + k < n; i += k) {
    const ang = Math.atan2(pts[i + k].y - pts[i].y, pts[i + k].x - pts[i].x)
    if (prev !== null) sum += normDeg((ang - prev) * DEG)
    prev = ang
  }
  return Math.abs(sum)
}

/* ★★ 判"这一笔是不是绕回来合上了"。两条都要过，但**分工完全不同**：
 *
 *   ① 净转角 ≥ NET_TURN_CLOSED —— **这才是判据**。它把"绕回来的圈"和
 *      "来回划的线 / 折线 / 写字的撇折"干干净净地分开（见 netTurn 的注释）。
 *   ② 端点别离得太远（CLOSE_RATIO）—— 只是**松预筛**，用来挡住
 *      "净转角很大、但明显不是要闭合"的那一类（比如绕了大半圈停在别处的长弧）。
 *      ⚠ 它必须**松**，因为真人画圈常常多绕一小截收笔（1.2 圈时这里是 0.42）。
 *
 * ★ 为什么不能只要 ②：端点距离分不开"闭合"和"来回划"（后者首尾也可能重合）。
 * ★ 为什么不能只要 ①：一条像"逗号"那样绕了大半圈再甩出去的长弧，净转角也能到 200°+，
 *   而它显然不是要闭合 —— 那类笔迹首尾离得很远，② 正好挡得住。
 *   两条正交，缺一条就有一类错判。 */
function isClosed(pts) {
  if (closureRatio(pts) > CLOSE_RATIO) return false
  return netTurn(pts) >= NET_TURN_CLOSED
}

function diagOf(pts) {
  let x0 = pts[0].x, y0 = pts[0].y, x1 = pts[0].x, y1 = pts[0].y
  for (const p of pts) {
    if (p.x < x0) x0 = p.x
    if (p.x > x1) x1 = p.x
    if (p.y < y0) y0 = p.y
    if (p.y > y1) y1 = p.y
  }
  return Math.hypot(x1 - x0, y1 - y0)
}

/** 整条路径的长度。 */
function pathLen(pts) {
  let s = 0
  for (let i = 1; i < pts.length; i++) s += dist(pts[i - 1], pts[i])
  return s
}

/* 把一笔的坐标**归一化**：减去包围盒左上角。
   ★ 为什么：识别是在世界坐标里做的，而世界坐标可能有很大的平移
     （用户的板画在 (50000, 30000) 一带）。所有和"尺寸"有关的比值不受影响，
     但**任何和"绝对坐标"有关的量**（比如"这一点在不在第一象限"）会。
     归一化之后判读只依赖形状本身 —— 这比"让所有阈值都乘一个尺度"稳得多。
   ⚠ fitShape 要**反归一化回去**（加回偏移），否则规整出来的形状会跑到原点。 */
function normalize(pts) {
  let x0 = pts[0].x, y0 = pts[0].y
  for (const p of pts) {
    if (p.x < x0) x0 = p.x
    if (p.y < y0) y0 = p.y
  }
  return { pts: pts.map((p) => ({ x: p.x - x0, y: p.y - y0, p: p.p })), ox: x0, oy: y0 }
}

// ─────────────────────────────── 直线 ───────────────────────────────

/* 直线：首尾连一条弦，看所有点离弦多远（相对弦长），以及沿路的累计转角。
 *
 * ⚠ 它排在**最后**被判（见 recognizeShape 的顺序）：矩形/三角形的边也很直，
 *   但它们的"笔"是个闭合回路 —— 闭合的先被多边形/圆认走，剩下不闭合的才轮到直线。
 *   顺序搞反的话，一个画得很糙的三角形会被判成"一条弯回来接上的线"。
 */
function fitLine(pts) {
  if (pts.length < 2) return null
  const a = pts[0]
  const b = pts[pts.length - 1]
  const chord = dist(a, b)
  if (chord < MIN_DIAG) return null
  let maxD = 0
  for (const p of pts) {
    const d = pointSegDist(p, a, b)
    if (d > maxD) maxD = d
  }
  const sag = maxD / chord
  if (sag > LINE_MAX_SAG) return null

  /* ★★ 有符号弓形面积（除以弦长² 归一化）—— **这一条是直线的真正判据**，
   *   2026-09-19 加的，来历值得记下来（它是"直线认不出来"那件事的正解）。
   *
   * 为什么要它（`sag` 和 `netTurn` 各自有一个洞）：
   *   · **`sag` 分不开"弧"和"直线"。** 它量的是"离弦**最远**多少"，
   *     而一条**对称**的弧，离弦最远处就在中点 —— 它的 sag 可以很小。
   *     实测真板上两笔明显是弯的线（点沿弦的偏移从 0 拱到 6.5 / 10.9 再回来），
   *     sag 只有 0.0315 / 0.0443 —— 和"手抖得厉害一点的直线"（0.0315）**完全重叠**。
   *   · **`netTurn` 在"点少"时会退化成噪声。** 抽稀之后一条真直线只剩 4~15 个点，
   *     `floor(n/8)` 掉到 1 ⇒ 逐点算方向 ⇒ 逐步转角在 ±10~15° 之间正负交替
   *     （实测净转角虚增 10.88°）。这一条我现在用 `MIN_DIR_STEP_PX` 压了一部分，
   *     但残余仍然把真直线的分数拖到 0.55 上下。
   *
   * ★ 面积这个量**两个洞都不吃**：
   *   · 它按"点在哪一侧"累积，手抖是**零均值**的 ⇒ 正负相消，不累积
   *     （netTurn 的残余累加在这里天然被消掉）；
   *   · 弧是**单侧**的 ⇒ 整条弧的面积都往一个符号上加，**不靠"最大值"取胜**
   *     （sag 的洞被补掉了）。
   *
   * ★ 标定（实测，全都量过）：
   *   合成手画直线（16 点、抖幅 ±0.3 ~ ±2.5px）：|面积| = **0.0009 ~ 0.011**
   *   真板弦 ≥ 110 的笔里最"直"的几笔：            |面积| = **0.0012 ~ 0.0037**
   *   真板上明显是弧的（sag ≥ 0.15）：              |面积| = **0.07 ~ 0.99**
   *   ⇒ 中间有近一个数量级的空档，取 **0.03**（比"最抖的直线"大一倍半、
   *     比"最平的弧"小一半），两边都留着余地。
   * ⚠ 调小会放进"画得很平的弧"；调大一点没关系（直线本来就在 0 附近）。
   *   我取偏保守的那一侧（宁可漏掉一条画得很难看的直线，也不许把弧拉直）。 */
  const area = signedArea(a, b, pts) / (chord * chord)
  if (Math.abs(area) > LINE_MAX_AREA) return null

  /* ★ 用**净转角**（正负相消），不是"绝对值之和"（见 LINE_MAX_TURN 的注释）。
     净转角对手抖不敏感（抖是零均值的），但对"真拐弯"极其敏感。
     ★ 它是**粗筛**（挡"折线 / 来回划"），不是分数的主力 —— 见下面。 */
  const turn = netTurn(pts)
  if (turn > LINE_MAX_TURN) return null

  /* ★★ 分数：**以面积为主**，转角只做一票否决式的小修正。
   *
   * ⚠ 原来写的是 `min(1 - sag/闸, 1 - turn/闸)` —— 两个都以**闸值**归一。
   *   问题出在 `turn`：手画直线的净转角分布是 0.7°~17.5°（实测量到 17.5°），
   *   而闸在 24° —— 于是一条**转 10.3° 的真直线**（真板上量到的那一笔）
   *   只拿 `1 - 10.3/24 = 0.571` 分，被 `MIN_SCORE = 0.62` 刷掉。
   *   也就是说：**用一个"及格线"当分母，等于把及格线本身当成了满分线。**
   *   闸是拿来"不许过"的，不是拿来衡量"有多好"的 —— 这两件事混在一起，
   *   结果就是"刚好及格的形状"永远拿不到及格分。
   *
   * ★ 现在的分数按**实测的典型值**归一：面积用 `LINE_TYPICAL_AREA`（0.011，
   *   就是"抖 ±2.5px 的直线"那个量级），转角用 `LINE_TYPICAL_TURN`（18°，
   *   实测手画直线的上沿）。这样"一条真直线"拿高分、"一条勉强过闸的"拿低分 ——
   *   排序才有意义（界面拿 score 排序/显示"有多像"）。 */
  const sArea = 1 - Math.abs(area) / LINE_TYPICAL_AREA
  const sTurn = 1 - turn / LINE_TYPICAL_TURN
  const score = Math.min(clamp01(sArea), clamp01(sTurn))
  /* ⚠ `sag` 不进分数：它和面积高度相关（都量"离弦多远"），
   *   而面积更准（见上面那个洞）。两个相关的量一起用只会让"最差的那个"主导。 */
  return { kind: 'line', a, b, score, closed: false }
}

/* 点集相对"弦 a→b"的**有符号**弓形面积（叉积和的一半）。
   正负表示点整体偏在弦的哪一侧 —— 判"是不是直线"时只用它的绝对值，
   但它有符号这一点正是"弧"和"手抖"的分水岭（见 fitLine 里那段）。 */
function signedArea(a, b, pts) {
  let s = 0
  for (let i = 0; i + 1 < pts.length; i++) {
    const p = pts[i]
    const q = pts[i + 1]
    s += ((p.x - a.x) * (q.y - a.y) - (q.x - a.x) * (p.y - a.y)) / 2
  }
  return s
}

/** 点到线段距离（和 geometry.js 里那个同算法；这里要的是"离弦多远"）。 */
function pointSegDist(p, a, b) {
  const dx = b.x - a.x
  const dy = b.y - a.y
  const L2 = dx * dx + dy * dy
  if (L2 === 0) return Math.hypot(p.x - a.x, p.y - a.y)
  let t = ((p.x - a.x) * dx + (p.y - a.y) * dy) / L2
  t = Math.max(0, Math.min(1, t))
  return Math.hypot(p.x - (a.x + t * dx), p.y - (a.y + t * dy))
}

/* 对一笔做滑动平均（窗宽 win 个点，两端取可用的那一段）。
 *
 * ★ 为什么非得平滑：下面要做"按弧长重采样"，而**弧长是沿噪声量的**。
 *   采样噪声让路径自己弯来弯去，量出来的弧长**永远比真实弧长大** ——
 *   不平滑直接重采样，等于按"噪声的路径长"分配采样点，质心照样跑偏。
 * ⚠ 窗宽不能太大：要压掉 4px 左右的采样噪声，几个点就够；
 *   窗宽太大会把"手画的椭圆"也压圆（把要认的特征抹掉）。 */
function smoothPoints(pts, win) {
  const n = pts.length
  if (n < 3 || win < 2) return pts
  const half = Math.floor(win / 2)
  const out = new Array(n)
  for (let i = 0; i < n; i++) {
    const lo = Math.max(0, i - half)
    const hi = Math.min(n - 1, i + half)
    let sx = 0, sy = 0
    for (let k = lo; k <= hi; k++) { sx += pts[k].x; sy += pts[k].y }
    const c = hi - lo + 1
    out[i] = { x: sx / c, y: sy / c, p: pts[i].p }
  }
  return out
}

/* 按弧长把一笔**等距重采样**成 count 个点（首尾都在）。
 *
 * ★ 目的：让每个采样点代表**等长的一段弧**。这样后面的质心、半径统计
 *   都与"用户笔走得多快"无关（手写采样是按时间的，慢的地方点就密）。
 * ⚠ 传进来的点**必须先平滑**（见 smoothPoints）：噪声会把弧长撑大。 */
function resampleByArc(pts, count) {
  const n = pts.length
  if (n < 2) return pts
  const acc = [0]
  for (let i = 1; i < n; i++) acc.push(acc[i - 1] + dist(pts[i - 1], pts[i]))
  const total = acc[n - 1]
  if (!(total > 0)) return pts
  const out = []
  let j = 0
  for (let q = 0; q < count; q++) {
    const target = (total * q) / (count - 1)
    while (j < n - 2 && acc[j + 1] < target) j++
    const seg = acc[j + 1] - acc[j]
    const u = seg > 0 ? (target - acc[j]) / seg : 0
    out.push({
      x: pts[j].x + (pts[j + 1].x - pts[j].x) * u,
      y: pts[j].y + (pts[j + 1].y - pts[j].y) * u,
      p: pts[j].p,
    })
  }
  return out
}

/* ★★ 剪掉"收笔多绕"的那一段：从起点出发沿路径走，找到**接缝**（真正绕回来的那一点），
 *   之后的点全部丢掉。专给 `fitCircle` 求质心用（理由写在那一处，很长的注释）。
 *
 * ── 判据怎么选（这一步我换过三版，每版的反例都记着）──
 *
 * ❌ 第一版："离起点的直线距离 < 总弧长 2%"。结果**剪过了头**：半径 80 的圆上，
 *    2% 的容差是 5.5px，而圆在"接缝"附近离起点的距离变化很慢（切向），
 *    于是判据从接缝**再往前**多吃了十几个点。症状是偏移方向从 0°（被重叠拉向起点）
 *    翻成 **178°**（被剪掉的那段拉向反侧）—— 从 6px 变成 0.85px，看着"好了"，
 *    其实只是换了个方向的错。**"变小的错"最危险，它看起来像修好了。**
 *
 * ✅ 第二版：**找"离起点最近"的那一点**（i 从 45% 或"走过的弧长超过总长 60%"之后开始找）。
 *    ⚠ 为什么是 45% 这个底：**必须**躲开"起笔那一下在原地抖"。
 *      手写起笔常常头几个点离起点很近（那不是"绕回来"，是"还没走开"）——
 *      不加这个底，接缝会被判在起点旁边，那一笔就被剪成一小段，圆心朝反方向偏。
 *    ⚠ 我原来这一版写的是"闭合回路周长最短"（`acc[i] + 回到起点的距离`）——
 *      **那是错的，而且是"看起来很有道理"的那种错**：`acc[i]` 单调增，所以那个和在
 *      i 很小的时候天然就最小，最小值永远落在搜索区间的**下界**上（实测每个重叠角都
 *      恰好报 cut=72 = 45% 那个下界）。症状是"改了代码但结果一个数都没变"，
 *      极容易误判成"没生效 / 没编译进去"。
 *      ⇒ 教训：**判据里只要有一项是单调的，这个判据就会退化成"取端点"。**
 */
function trimOverlap(pts) {
  const n = pts.length
  if (n < 16) return pts
  const acc = [0]
  for (let i = 1; i < n; i++) acc.push(acc[i - 1] + dist(pts[i - 1], pts[i]))
  const total = acc[n - 1]
  if (!(total > 0)) return pts

  const x0 = pts[0].x
  const y0 = pts[0].y
  let cut = -1
  let best = Infinity
  for (let i = 1; i < n; i++) {
    /* ★ 两道底：走过的弧长要过半，而且点数也要过半 ——
       否则"起笔原地抖"会被当成接缝。 */
    if (acc[i] < total * 0.5) continue
    if (i < n * 0.5) continue
    const d = Math.hypot(pts[i].x - x0, pts[i].y - y0)
    if (d < best) { best = d; cut = i }
  }
  if (cut < 0 || cut < n * 0.5) return pts
  return pts.slice(0, cut)
}

/* ⚠ 这里原本有一个 `totalTurn`（沿路径的**绝对值之和**），已经删掉。
   删它的理由（重要，别再写回来）：
   绝对值之和把**零均值的采样抖动**全变成正数累加起来 —— 一条**笔直的线**
   实测报出 76°~292° 的"累计转角"，阈值 24 全部判死。
   方向抖动是零均值的，所以正确的问题是"**净**转过去多少"（正负相消），
   也就是 `netTurn`。"一共抖了多少下"根本不是几何量。

   顺带记下同时踩到的那个角度坑（`normDeg` 存在的理由）：
   角度差写成 `|a2-a1| > 180 ? 360-|a2-a1| : |a2-a1|` 看着对，但在
   "真实转角接近 180°"那一小段是错的 —— 先取绝对值就把"该往哪边绕"的信息丢了。
   正确写法：**先做差 → 归一化到 (-180,180] → 最后取绝对值**。 */

/** 把角度差归一化到 (-180, 180] —— 两条方向之间**实际转过**多少度。 */
function normDeg(d) {
  let x = d % 360
  if (x > 180) x -= 360
  if (x <= -180) x += 360
  return x
}

