/* ── 分段：找一笔上"最像角的若干个点" ─────────────────────────────────────
 *
 * ══ 为什么不用"贪心切段"（我写了三版，全废）══
 *
 * 前三版都是"从左往右走，够条件就切一刀"的贪心。全部栽在**阈值对采样噪声极敏感**上：
 *
 *   v1 按"离弦多远"切 → 离弦距离和边长成正比，长边**中点**离弦当然远，
 *      于是长边从中间被劈开。实测：方方正正的矩形数出 92°,87°,48°,44°。
 *   v2 按"相邻两小步方向差"切 → 一小步的方向是纯噪声，矩形数出 **63 个角**。
 *   v3 按"整段方向 vs 当前方向"切 + 角位后撤 → 还是在 4 个角和 30 个角之间来回摆，
 *      取决于后撤循环怎么写 —— 因为我是在**用阈值去贴样本**，不是在建模型。
 *
 * ★ 根本问题：**"这里是不是一个角"不该由一连串局部阈值临时决定。**
 *   正确的问法是："**如果用 n 个角 + 直边去重建这一笔，重建得多像？**"
 *   于是变成一个有明确目标的**全局**问题：对 n = 3,4,5… 各求最优的 n 个角，
 *   比较它们的重建误差。角太少 → 重建贴不住（误差大）；角太多 → 过拟合
 *   （多一个自由度，误差必然更小，所以要**惩罚**它）。
 *
 * 这就是下面两件事的分工：
 *   · `piecewiseFit`  给定"分成 n 段"，求**最优的**切点（动态规划，全局最优）；
 *   · `bestCorners`   在 n 之间选，判据 = 误差 + 复杂度惩罚（和 AIC 一个精神）。
 *
 * ⚠ 段数上限刻意很小（MAX_SEG = 6）：我们要认的是"直线/三角/矩形/圆"，
 *   一个手画图形需要的段数超过 6，它就不是我们要认的东西了。
 */

/* 一笔按"nSeg 段折线"重建的**全局最坏偏离**（离弦最大距离），
 * 以及取到它的那组切点。
 *
 * 动态规划：dp[k][j] = "前 j 个点分成 k 段"时，**各段最坏偏离的最大值**的最小可能值。
 * ★ 代价用 max（取最坏的那一段）而不是 sum：
 *   和 score 一路取 min 是同一个精神 —— "最坏的那一段有多坏"才是判据，
 *   不能让"很多段都很好"去掩盖"有一段完全贴不住"。
 *
 * 复杂度 O(n²·nSeg)，n 是点数（手写一笔几百点），nSeg ≤ 6 —— 够快。
 *
 * ★ closed = true 时额外算一个"**接缝角**"：
 *   一笔闭合的图形，首尾落在**同一个角**上。可 DP 的切点里第一个和最后一个点
 *   是边界、不算角 —— 于是四角矩形只数出三个、三角形只数出两个（实测就是少的这一个）。
 *   处理：把"最后一个切点 → 起点"这条**在数据里不存在、但图形上有**的边也算进代价。
 *   只要它贴得住，就说明首尾相接处确实是一个角 → 角数 +1。
 */
function piecewiseFit(pts, nSeg) {
  const n = pts.length
  if (n < nSeg + 1) return null
  /* cost[i][j]：i..j 这一段的"最坏偏离"（点离 i→j 弦的最大距离） */
  const cost = (i, j) => {
    const a = pts[i]
    const b = pts[j]
    let maxD = 0
    for (let k = i + 1; k < j; k++) {
      const d = pointSegDist(pts[k], a, b)
      if (d > maxD) maxD = d
    }
    return maxD
  }
  /* 段太短（同一点或挨着）不许切：小于 MIN_SEG_PTS 个点的段没意义 */
  const minPts = MIN_SEG_PTS

  const INF = Infinity
  /* dp 存"最小值"，从 k=1 递推到 nSeg */
  let prev = new Array(n).fill(INF)
  prev[0] = 0
  const backs = []
  for (let k = 1; k <= nSeg; k++) {
    const cur = new Array(n).fill(INF)
    const bk = new Array(n).fill(-1)
    for (let j = k * minPts; j < n; j++) {
      let best = INF
      let bi = -1
      for (let i = (k - 1) * minPts; i <= j - minPts; i++) {
        if (prev[i] === INF) continue
        const v = Math.max(prev[i], cost(i, j))
        if (v < best) { best = v; bi = i }
      }
      cur[j] = best
      bk[j] = bi
    }
    backs.push(bk)
    prev = cur
  }
  if (prev[n - 1] === INF) return null

  /* 回溯切点 */
  const cuts = [n - 1]
  let j = n - 1
  for (let k = nSeg - 1; k >= 0; k--) {
    const i = backs[k][j]
    if (i < 0) return null
    cuts.push(i)
    j = i
  }
  cuts.reverse()
  if (cuts[0] !== 0) return null

  let worst = 0
  for (let k = 1; k < cuts.length; k++) worst = Math.max(worst, cost(cuts[k - 1], cuts[k]))
  return { cuts, worst }
}

/* ★★ "接缝角"能不能算一个角 —— 判据是**首尾这两个点是不是同一个点**。
 *
 * 背景：一笔闭合的图形，首尾落在**同一个角**上（画矩形"回来合上"的地方）。
 *   而 DP 的切点里第一个和最后一个点永远是边界、不算角 ——
 *   所以四角矩形只会数出三个角、三角形只数出两个，**永远少一个**。
 *   修法就是：首尾真的是同一个点 ⇒ 那里有一个角 ⇒ 角数 +1。
 *
 * ⚠⚠ 这里踩了一个很贵的错，记下来免得改回去：
 *   一开始写的是"量 `最后切点 → 起点` 那条边、看中间的点离它多远"（下面记成旧写法），
 *   而 `fitCorners` 传进来的 `from` **永远是 cuts 的最后一个 = n-1**：
 *   那个循环 `for (k = from+1; k < n; k++)` 于是**一次都不跑**，`maxD` 恒为 0，
 *   `0 <= worstCap` 恒成立 —— **闸是空的，`seam` 恒为 true**。
 *   实测 10 个样本全 true，包括 198° 的开口弧（首尾差 179px）和一条"折线三弯"
 *   （首尾差 332px）：那两类根本没有接缝，却白捡了一个角。
 *   → 后果是 `nCorners` 对**每一笔**都多算一个，`rectLike` / `fitTriangle`
 *     的"角数正好等于 n"整个建立在这个空闸上。
 *
 * ★ 正确的判据（现在这条）：首尾两个点的**距离**够不够近（相对对角线）。
 *   近 ⇒ 它们是同一个点 ⇒ 那里本来就是一个角，DP 漏掉了它 ⇒ +1。
 *   远 ⇒ 这一笔压根没绕回来（开口弧、折线），接缝不存在 ⇒ 不 +1。
 *   它和旧写法最大的不同：**这个量在"开口"那一侧会真的变大**，所以闸是有效的。
 *   ⚠ 它必须是**松**的（多绕一小截收笔时首尾会离得比较远，见 closureRatio 的注释）。
 */
function seamIsReal(pts) {
  return closureRatio(pts) <= CLOSE_RATIO
}

/* 一笔"几个角"的全局判读。
 *
 * ★ 角数怎么定：对 nSeg = 2,3,4,… 各求最优分段，比"误差 + 复杂度惩罚"。
 *   惩罚项是必须的：多一段**必然**让误差变小（多一个自由度），
 *   不罚的话永远选段数最多的那个 —— 那就又回到"过拟合"了。
 *   取 penalty = 对角线的 1.5%（每多一段的代价）：
 *   一段真边带来的误差下降远超它；而切一段噪声带来的下降几乎为零 → 被罚掉。
 *
 * ⚠⚠ 闭合图形有个**必踩的坑**：这条笔的首尾落在同一个角上（画矩形"回来合上"的地方），
 *   而 DP 的切点里，**第一个点和最后一个点永远是边界，不算角**。
 *   所以一个四角矩形只会数出**三个**角、三角形只数出**两个** —— 永远少一个。
 *   实测就是这么回事（矩形 93°,90°,89° 三个、三角 125°,109° 两个）。
 *   修法：闭合的时候，首尾合起来那个角要单独补一个 ——
 *   **判据是"首尾两个点是不是同一个点"**（见 seamIsReal）。
 *
 * 返回 { corners, worst, nSeg, cuts, diag, seam } 或 null。corners 是**点的下标**。
 */
function fitCorners(pts, maxSeg = MAX_SEG, closed = false) {
  const diag = diagOf(pts)
  if (!diag) return null
  const pen = diag * CORNER_PENALTY
  /* ★ 接缝角：首尾是不是同一个点 —— 是的话那里有一个角（+1）。
     这是矩形从 3 个角变 4 个的那一下。判据见 seamIsReal（它是个**真的会失效**的闸）。
     ⚠ 它和"分成几段"无关（只问首尾两个点），所以算在循环外面。 */
  const seam = closed && seamIsReal(pts)
  let best = null
  for (let k = 2; k <= maxSeg; k++) {
    const f = piecewiseFit(pts, k)
    if (!f) continue
    const worst = f.worst
    const obj = worst + (k - 2) * pen
    if (!best || obj < best.obj) best = { ...f, nSeg: k, obj, seam, worst }
  }
  if (!best) return null
  /* 两个端点不算角（它们是笔的开头和结尾）——
     闭合的时候，首尾合起来那个角由 seam 单独计。 */
  const corners = best.cuts.slice(1, -1).filter((i) => i >= 0)
  return { corners, worst: best.worst, nSeg: best.nSeg, cuts: best.cuts, diag, seam: best.seam }
}

/* 各拐角处的外角（度）：按"n 段折线最优重建"拿到的角，逐个量两边的方向差。
 *
 * 返回 [{ i, deg }]，i 是角在点数组里的下标（接缝角用 i = 0 表示"首尾相接处"）。
 *
 * ★ 外角算法用 normDeg —— 和 totalTurn 里那个坑**一模一样**：
 *   方向差必须"先做差、再归一化到 (-180,180]、最后取绝对值"。
 *   写成 `|a2-a1| > 180 ? 360-|a2-a1| : |a2-a1|` 在大部分区间看着也对，
 *   但它在"真实转角接近 180°"那一小段是错的（那正是"两条边几乎反向"的情形）。
 *   不留这种窄缝。 */
function cornerTurns(pts) {
  const closed = isClosed(pts)
  const f = fitCorners(pts, MAX_SEG, closed)
  if (!f) return []
  const cuts = f.cuts
  const dirOf = (a, b) => Math.atan2(b.y - a.y, b.x - a.x)
  const out = []
  const n = pts.length
  const last = n - 1
  /* 内部切点：前一段和后一段都在数据里 */
  for (let k = 1; k < cuts.length - 1; k++) {
    const prev = pts[cuts[k - 1]]
    const cur = pts[cuts[k]]
    const next = pts[cuts[k + 1]]
    out.push({ i: cuts[k], deg: Math.abs(normDeg((dirOf(cur, next) - dirOf(prev, cur)) * DEG)) })
  }
  /* ★ 接缝角：整条笔的**起点**（闭合图形上首尾相接的那个角）。
     它前面那条边 = 最后一条**完整**的边（"倒数第二个切点 → 最后一个切点"）；
     后面那条边 = "起点 → 第一个切点"。
     ⚠⚠ 这里踩过两个坑，都是"拿哪一段量方向"的问题：
       ① 一开始量成 `dir(最后切点 → 起点)`：把首尾之间那条**闭合缝隙**也算进去了，
          方向完全不对（矩形接缝角算成 131°/145°/172°）。
       ② 改成 `dir(最后切点 → 笔的末尾)`：更糟 —— 实测"最后切点"几乎就压在起点上
          （矩形：切点在 (9.5,6.2)，起点在 (6.4,3.3)，相距 3px），
          于是这条"边"只是一根 3px 的小尾巴，方向是纯噪声，接缝角算成 0.9°。
     ★ 正确做法：**用倒数第二个切点到最后一个切点**那一段 ——
       那是最后一根**真的、够长的**直边，方向可靠。
       这两个切点之间隔着整条边（矩形实测 95→119 一整条），不是小尾巴。 */
  if (f.seam && cuts.length >= 3) {
    const beforePrev = pts[cuts[cuts.length - 2]]
    const before = pts[cuts[cuts.length - 1]]
    const start = pts[0]
    const after = pts[cuts[1]]
    out.push({ i: 0, deg: Math.abs(normDeg((dirOf(start, after) - dirOf(beforePrev, before)) * DEG)) })
  }
  return out
}

/* 矩形：闭合 + 四个明显的直角 + 边是直的。
 *
 * ★ 为什么用"四个角"而不是"包围盒贴合度"：
 *   一个歪歪扭扭的四边形也能"大体填满它的包围盒"，所以贴合度是个**很松**的判据 ——
 *   那正是 ADR-0001 里"直度中位 0.28 也能通过"的那种松。
 *   数角是**离散**的判据：要么有四个角，要么没有。
 *
 * 顺序上**先判矩形再判三角形**：一个画得很糙的矩形，角上多点小拐弯，
 * 4 个主角之外可能多出一两个小角 —— 先按三角形判会得到"3 个角"（挑最大的三个），
 * 于是正方形被认成三角形。所以矩形这边的判据是"**至少**四个角、且四个主角接近直角"。
 */
function fitRect(pts) {
  const r = rectLike(pts, 4)
  if (!r) return null
  return { kind: 'rect', box: r.box, score: r.score, closed: true }
}

/** 矩形/三角形共用的"是不是这个正多边形"的判读。n = 4 或 3。 */
function rectLike(pts, n) {
  if (!isClosed(pts)) return null
  const f = fitCorners(pts, MAX_SEG, true)
  if (!f) return null
  /* ★ 角数的算法：内部切点数 + （接缝那个算不算一个角）。
     这里**不**用"挑最大的 n 个角"那种松做法 —— 那正是正方形被认成三角形的原因：
     一个糙矩形多出的小角会被当成"第三个顶点"。
     现在 fitCorners 已经**全局**定好了有几个角（重建误差 + 复杂度惩罚），
     所以直接要求"角数正好是 n"，多一个少一个都不认。 */
  const nCorners = f.corners.length + (f.seam ? 1 : 0)
  if (nCorners !== n) return null
  /* 这几段贴不住这一笔 → 不是在画多边形（一个圆用 4 段贴，误差会远超阈值） */
  if (f.worst > f.diag * FIT_WORST_MAX) return null

  const turns = cornerTurns(pts).map((x) => x.deg)
  if (turns.length !== n) return null

  /* 平均外角要接近"正 n 边形的外角"（360/n）：矩形 90°、三角形 120°。容差 ±30%。
     ★ 这一条是"直角"的判据：一个**菱形**（角是 60/120）平均外角也是 90 上下，
       但它偏得够多（60 和 120 差 90 有 30），会被这一条按 ±30% 卡掉。
       要它更严可以收紧这个数，但真人画的直角本身就偏（实测常见 75~105°）。 */
  const want = 360 / n
  const avg = turns.reduce((s, d) => s + d, 0) / n
  if (Math.abs(avg - want) > want * 0.3) return null
  /* 每个角都不能太小：一个 20° 的"角"是噪声，不是顶点。 */
  if (Math.min(...turns) < CORNER_MIN_TURN) return null

  /* 边也要够直 —— 判据用"整条路径的长度 / 包围盒周长"。
     正多边形的这个比值接近 1（矩形）或略大于 1；一条又扭又绕的线会明显大于它。
     ★ 它和上面 worst 那道闸是**互补**的：worst 管"每一段贴不贴得住弦"，
       这个比值管"整条笔迹绕了多少冤枉路"（一个内凹的图形每段都能贴住，
       但总长会明显超过包围盒周长）。 */
  const box = bboxOf(pts)
  const perim = 2 * (box.w + box.h)
  if (perim > 0) {
    const lonRatio = pathLen(pts) / perim
    const cap = n === 4 ? 1.5 : 1.7 // 三角形的斜边让实际周长比包围盒周长小，所以更松
    if (lonRatio > cap) return null
  }

  const score = clamp01(1 - Math.abs(avg - want) / (want * 0.3))
  return { box, score, turns: avg }
}

function bboxOf(pts) {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity
  for (const p of pts) {
    if (p.x < x0) x0 = p.x
    if (p.x > x1) x1 = p.x
    if (p.y < y0) y0 = p.y
    if (p.y > y1) y1 = p.y
  }
  return { x: x0, y: y0, w: x1 - x0, h: y1 - y0 }
}

/* 三角形：闭合 + 三个角。
   判据比矩形松一点（三角形的角本来就偏得厉害：手画的"等边"常在 40~80°）。 */
function fitTriangle(pts) {
  if (!isClosed(pts)) return null
  const f = fitCorners(pts, MAX_SEG, true)
  if (!f) return null
  const nCorners = f.corners.length + (f.seam ? 1 : 0)
  if (nCorners !== 3) return null
  if (f.worst > f.diag * FIT_WORST_MAX) return null
  const turns = cornerTurns(pts).map((x) => x.deg)
  if (turns.length !== 3) return null
  /* 三个主角的外角和必须接近 360°。这一条是真正的判据 ——
     它同时保证"是个闭合的多边形"（三角形外角和恒为 360°）。
     ±25% 的容差：手画的三角形三个角加起来还是会接近 360（这是几何事实，不是手感），
     偏的只可能是"我在某处多算了/少算了一个角"。 */
  const sum = turns.reduce((s, d) => s + d, 0)
  if (Math.abs(sum - 360) > 360 * 0.25) return null
  /* 角不能太小：三个 20° 的"角"其实是同一处手抖被拆成了三份。 */
  if (Math.min(...turns) < CORNER_MIN_TURN) return null

  const box = bboxOf(pts)
  const perim = 2 * (box.w + box.h)
  if (perim > 0 && pathLen(pts) / perim > 1.9) return null

  const score = clamp01(1 - Math.abs(sum - 360) / (360 * 0.25))
  return { kind: 'triangle', box, score, closed: true, turns, cuts: f.cuts }
}

// ─────────────────────────────── 圆 / 椭圆 ───────────────────────────────

/* 圆：闭合 + 所有点到**拟合圆心**的距离一致。
 * 圆心用"点的平均值"（质心）—— 对手画的**闭合**圈来说它足够准，而且没有迭代、没有不稳定。
 * ⚠ 别用"包围盒中心"：手画的圆在一侧常常多绕半圈（收笔叠过去），
 *   包围盒会被那一小段拽偏，质心抗这个。
 * 椭圆：同一套，只是把 x/y 各除以自己的半轴再比（"归一化成圆再看"）。
 */
function fitCircle(pts) {
  if (!isClosed(pts)) return null
  const box = bboxOf(pts)
  const diag = Math.hypot(box.w, box.h)
  if (diag < MIN_DIAG) return null

  /* ★★ 求圆心：**先平滑、再按弧长重采样**，然后取质心 —— 不能直接按点数平均。
   *
   * 手写一笔的点是**按时间**采的：笔走得慢的地方点就密。而人画圆时速度很不均匀
   * （起笔慢、收笔快、拐弯处还会停一下），于是"按点数平均"出的质心会明显偏向慢的那一侧。
   *
   * ⚠ 注释里原来写的是"会**略微**偏向，对判定够了" —— 实测**完全不是"略微"**：
   *   一个真半径 80 的圆，只要半圈画得慢一点（完全正常的手写），
   *   按点数平均的质心偏移就到 **33px**（占半径的 41%），
   *   半径中位数报 **62**（真值 80），拟合分 **0.000** —— 画得好好的圆直接认不出来。
   *   不均匀采样在真人手写里是**常态**，所以这会让功能在第一个真圆上就失效。
   *
   * ⚠⚠ 也**不能**"按相邻点距离加权"（我试过，只把 33px 降到 19px，仍然认不出来）：
   *   慢速区相邻点间距小到 **0.5px**，而采样噪声是 **4px** 量级 ——
   *   那里"邻点距离"量到的几乎全是噪声，不是弧长。
   *   实测一圈里相邻间距从 0.5px 到 220px 跨了 440 倍，噪声把权重彻底泡坏了。
   *
   * ★ 正确做法（两步，缺一不可）：
   *   ① **先平滑**：对点做一次滑动平均，把噪声压掉。不平滑的话"弧长"本身就是噪声的路径，
   *      而噪声路径**永远比真实路径长**（这是重采样这一类做法最容易踩的坑）。
   *   ② **再按弧长等距重采样**，然后取质心。此时每个采样点代表**等长的一段弧**，
   *      质心与"笔走得多快"完全无关。
   *   实测（同一个"半圈慢"的圆）：偏差 33px → **0.1px** 量级，半径中位数回到 80。
   */
  const smooth = smoothPoints(pts, SMOOTH_WIN)
  /* ★★★ 求质心之前，先**把收笔多绕的那一段裁掉** —— 这是这一族里最贵的一个 bug，
     值得从头写清楚。
   *
   * ⚠ 症状：自检里"规整出来的圆"逐点到圆心的距离，中位差 **0.696px**、最大 1.07px，
   *   而且逐点偏差是一条**完美的余弦波**（第 0 点 −1.066 → 第 34 点 +0.965 → 第 72 点 −1.066，
   *   正好一个周期）。这不是"画得不圆"，这是**圆心偏了**的样子：
   *   圆心偏 d，圆周上的点就会一半量出 r+d、一半量出 r−d。
   *   （因为量的时候用的是"我画的时候那个圆心"，所以偏差全记在了"不圆"头上。）
   *
   * ★ 真因：真人画圆到起点时**常常多绕一小截**再收笔（这是画得准的表现，
   *   文件里另一处注释也承认了这一点，并用 92 分位去容忍它）。
   *   而"按弧长等距重采样 + 取质心"这件事，对**首尾重叠**的曲线是**有偏的**：
   *   重叠的那一段在重采样时被走了两边 —— 它的权重**翻倍**了。
   *   于是质心被那段多出来的弧往**起点方向**拉。
   *
   * ★ 实测（半径 80、160 点、抖动 1.5px，绕行角度 = 360° × (1+重叠)）：
   *     重叠  0° → 质心偏 0.11px
   *     重叠  2° → 0.57px   重叠  5° → 1.22px   重叠 10° → 2.26px
   *     重叠 20° → 4.30px   重叠 30° → 6.17px   重叠 60° → 10.99px
   *   ⚠ 偏移的**方向**正好是"起点方向的一半角度"（10° → 5.0°、30° → 15.0°、60° → 30.0°），
   *     这就是"被重叠段拉走"的指纹 —— 没有任何别的解释会长成这个形状。
   *   更要命的是**半径和分数一起掉**：重叠 30° 时 r 报 79.39、score 0.85；
   *   重叠 60° 时 r 报 78.42、score 0.64 —— **再绕多一点这个圆就认不出来了**。
   *   也就是说：一个"画得特别准（绕着圆圈收笔）"的人，反而会被判成"没画圆"。
   *
   * ★ 修法：**把"回到起点之后"的那些点剪掉**，再做平滑/重采样/质心。
   *   剪的判据：沿路径走，第一次"离起点已经很近、而且已经绕出去超过半圈"的位置，
   *   就是收笔追上的地方，那里之后的全是重叠。
   *   ⚠ 为什么必须判"已经绕出去超过半圈"：起笔那一下笔可能原地抖两下，
   *     头几个点离起点**也很近**（那不是"绕回来"，是"还没走开"）。
   *     只按距离剪会把起笔那一段剪掉，圆心反而往另一边偏。
   */
  const body = trimOverlap(smooth)
  let cx = 0, cy = 0
  {
    const rs = resampleByArc(body, RESAMPLE_N)
    for (const p of rs) { cx += p.x; cy += p.y }
    cx /= rs.length
    cy /= rs.length
  }

  /* 半径 = 到质心的距离的中位数（比平均值抗"收笔那一段叠出来"的离群点）。 */
  const rs = pts.map((p) => Math.hypot(p.x - cx, p.y - cy)).sort((a, b) => a - b)
  const r = rs[Math.floor(rs.length / 2)]
  if (r < 4) return null

  /* 圆的判据：相对半径的误差，中位数 + 高分位两道。
     ★ 但相对误差要**扣掉一个绝对噪声底**（见 NOISE_FLOOR）：
       笔迹本身的采样噪声大约 3~4 世界像素，它是**与图形大小无关**的常数。
       对一个半径 200 的圆那是 2%（无所谓），对半径 40 的小圆就是 10% ——
       而"笔在抖"和"画得不圆"是两件事，不该让"画了个小圆"因此被判不圆。
       做法：把误差超出噪声底的那部分才算进判据。

     ⚠⚠ 第二个判据用**高分位（92%）而不是最大值**，这是踩出来的：
       真人画圆收笔时常常**多绕一小截**（画满一圈不停手，叠过去 10°~30°）。
       叠出去那一小段的位置整体比半径大一点点（它是"沿着圆再走一点"，
       但起点/终点那截会往外飘），于是 `maxErr` 被这**几个点**拖爆 ——
       实测一个正常的圆因此得 0 分而认不出来。
       但"叠出去一小截"根本不是"画得不圆"，它甚至说明用户画得很准
       （从头到尾都贴着圆才可能叠上）。
       统计上正确的问法是"**绝大多数**点贴不贴"，不是"最差的那一个贴不贴"，
       所以这里取 92 分位：容忍尾部 8% 的离群点（收笔/起笔那两小段）。
       ⚠ 不能干脆用"中位数 + 中位数"：那就完全放过了"有一段整体跑偏"——
         而"有没有一段跑偏"正是这道闸存在的理由（一个 C 形弧就靠它挡住）。 */
  const errs = rs
    .map((x) => Math.max(0, Math.abs(x - r) - NOISE_FLOOR) / r)
    .sort((a, b) => a - b)
  const medErr = errs[Math.floor(errs.length / 2)]
  const hiErr = errs[Math.min(errs.length - 1, Math.floor(errs.length * 0.92))]
  const circleScore = Math.min(1 - medErr / CIRCLE_MED_ERR, 1 - hiErr / CIRCLE_MAX_ERR)

  /* 椭圆的判据：把两个方向分开比。
     ★ 顺序：**先圆后椭圆**。一个正圆在两个方向上的半轴几乎一样，
       拿"椭圆"去贴当然也能贴上（还多一个自由度），但那是**过拟合**：
       它会把你画得稍微不那么圆的地方吸收进轴比里，结果"规整"出来的椭圆
       和你的原笔在观感上没有区别 —— 用户要的是"变规整"，那就要那版更像圆的。 */
  const w2 = box.w / 2
  const h2 = box.h / 2
  let ellipse = null
  if (w2 > 2 && h2 > 2 && (Math.max(w2, h2) / Math.min(w2, h2) >= ELLIPSE_MIN_RATIO)) {
    const ax = Math.max(w2, h2)
    const ay = Math.min(w2, h2)
    const scale = (ax + ay) / 2
    const er = pts.map((p) => {
      const dx = (p.x - cx) / ax
      const dy = (p.y - cy) / ay
      /* 同样扣噪声底：把"像素误差"换成"归一化空间的误差"再扣 */
      return Math.max(0, Math.abs(Math.hypot(dx, dy) - 1) - NOISE_FLOOR / scale)
    }).sort((a, b) => a - b)
    const eMed = er[Math.floor(er.length / 2)]
    /* 和圆那边同一个道理：用 92 分位而不是最大值（收笔多绕一小段不算"不椭"）。 */
    const eHi = er[Math.min(er.length - 1, Math.floor(er.length * 0.92))]
    const eScore = Math.min(1 - eMed / CIRCLE_MED_ERR, 1 - eHi / CIRCLE_MAX_ERR)
    ellipse = { kind: 'ellipse', cx, cy, rx: ax, ry: ay, score: clamp01(eScore), closed: true, box }
  }

  const circle = { kind: 'circle', cx, cy, r, score: clamp01(circleScore), closed: true, box }

  /* 椭圆和圆都成立时取分高的那个。★ 故意让圆有**同分优先**：
     上面说过，圆少一个自由度 —— 同分时它是更"克制"的解释。 */
  if (ellipse && ellipse.score > circle.score + 1e-6) return { shape: ellipse, circle, ellipse }
  return { shape: circle, circle, ellipse }
}

// ─────────────────────────────── 判读总入口 ───────────────────────────────

/* 顺序很重要，而且是有理由的（每一条都在下面写着）：
 *   ① 闭合的形状先判（矩形 → 三角形 → 圆/椭圆）—— 闭合是个**硬**事实，
 *      而"一条首尾接上的线"几乎必然也能通过直线判据（弦很短甚至为零）。
 *   ② 直线最后判。
 *   ③ 全都不过 → null（**什么都不做**，见文件头那条铁律）。
 */
export function recognizeShape(stroke) {
  const raw = toPoints(stroke && stroke.points)
  /* 太少的点连方向都算不出来。用户画快的时候一笔可能只有几个点 ——
     那时候"认不出来"是对的（信息真的不够）。 */
  if (raw.length < 6) return null

  const n = normalize(raw)
  const pts = n.pts
  const diag = diagOf(pts)
  if (diag < MIN_DIAG) return null // 一个点、一小勾：没有形状可言

  /* 荧光笔不算 —— 它是"划一下标记"，不是"画一个形状"。
     把它规整成一条直线会把用户的划重点变成一根尺子画的线。 */
  if (stroke.tool === 'highlighter') return null

  const closed = isClosed(pts)

  if (closed) {
    /* ★★ 采样够不够密 —— 两道闸，**只对闭合的形状用**（见下面 LINE_MIN_PTS 那段）。
     *
     * ⚠ 缺了它们，真板上那批"12~19 个点的碎笔迹"会**全数**通过，
     *   而且因为点太少、拟合毫无约束，拿到的分数**全是 1.000**。
     *   实测：用户 8 张板 6362 笔，加闸之前有 42 笔被认成形状，
     *   里面一多半是这种碎笔迹（画出来看就是一堆散点）。
     *
     * ★★ 为什么它俩**不能**管直线（2026-09-19 查出来的，代价是"直线一直认不出来"）：
     *   它俩是拿**闭合图形**的直觉定的，而直线那一侧的性质**正好相反**。
     *
     *   一、**抽稀之后的点数，物理含义和"采样密不密"无关。**
     *     存盘前会跑 `simplifyPoints(pts, 0.6)`（Board.jsx 收笔那一步），
     *     而它保留的是"**离弦 > 0.6px**"的点：
     *       · 一个圆/多边形：拐角处离弦必然很远 → 每角必留 2~3 点 → 点数有下限
     *         （四角矩形至少 10 点，实测规整后 5 点、判读时十几点）；
     *       · 一条**直线**：只有手抖的波峰能超过 0.6px → 留下的点数是
     *         "**手抖了几个波峰**"，和原始采样密度**几乎无关**。
     *     实测（模拟真手写、抖幅 ±1.5px）：200px 的线，原始 30 点 / 60 点 / 200 点，
     *     抽稀后**全都是 6 个点**；抖幅 ±0.5px 时只剩 4 点。
     *     ⇒ 一条笔直的线抽稀后只剩首尾 2 点，那是**正确**的表示（直线本来就不用密点）。
     *
     *   二、**真板上 122 笔几何上就是直线，点数全部 < 24（100% 被这道闸挡掉）。**
     *     点数的最大值是 22（弦 215px）——**整块板上没有任何一笔能过 24。**
     *     也就是说这道闸在真数据上等于"把整族功能关掉"：
     *     用户画一条直线，落到盘上是 4~10 点，永远认不出来。
     *     ⚠ 它**没有**保护到任何东西：把它从 24 放到 6，真板 6362 笔上
     *       直线命中数**恒为 0**（多出来的全是被圆那套宽松判据咬着的圆圈）。
     *
     *   三、**判"直不直"本来就不需要密采样。** `fitLine` 用的是
     *     `sag`（离弦最远 / 弦长）和 `netTurn`（净转角）—— 两个量和点数无关，
     *     对 3 点和 300 点的直线同样有效（`MIN_PT_DENSITY` 同理：抽稀后
     *     6 点 / 168px = 0.036，**必然**低于 0.12，它是在拿"写字"的特征卡"直线"）。
     *   ⇒ 所以直线走 `LINE_MIN_PTS`，而且**不吃密度闸**。
     */
    if (raw.length < MIN_PTS) return null
    /* ★★ 这里原来还有第二道闸 `raw.length / diag >= MIN_PT_DENSITY` —— **删掉了**（2026-09-19）。
       它就是用户报的「我画的比较大的时候会识别不出来」的根因，账记在 `MIN_PT_DENSITY`
       那个位置（文件上半部分，常量的老地方）—— 一句话：那个比值随尺寸**必然**下降。 */

    /* ★ 闭合的：先矩形、再三角形、再圆/椭圆。
       为什么矩形排在三角形前面：一个糙矩形可能多出一两个小角，
       按"最大的三个角"去凑三角形能凑出 360°（三个角当然能凑），
       于是正方形被认成三角形。让矩形先认，它要求四个角。 */
    const rect = fitRect(pts)
    if (rect && rect.score >= MIN_SCORE) return withOffset(rect, n)
    const tri = fitTriangle(pts)
    if (tri && tri.score >= MIN_SCORE) return withOffset(tri, n)
    const c = fitCircle(pts)
    if (c && c.shape.score >= MIN_SCORE) return withOffset(c.shape, n)
    /* 闭合但什么都不像（比如一个随手绕的圈）—— 不给结果。 */
    return null
  }

  /* ★★ 不闭合这一支：**只有直线**，而且它自己的闸和上面那两道完全不同。
   *
   * 点数：`LINE_MIN_PTS`（3）—— 判 sag / netTurn 只需要首尾 + 至少一个中间点
   *   来撑住"中间有没有鼓出来"。3 是**几何上最低**的要求，不是"采样够不够"。
   * ⚠ 这里**没有**密度闸，理由见上面那段（抽稀之后直线的点/像素必然很小）。
   *
   * ★ 那"汉字的横"不也会被认成直线吗？会 —— 而且这一直都会（放开前也一样，
   *   因为汉字横的点数本来就 < 24，从来没被点数闸挡过）。
   *   真正拦住它的是**弦长**那一道：`LINE_MIN_CHORD`。
   *   实测真板上 322 笔"几何上是直线"的笔，弦长中位只有 37px、
   *   90% 分位 82px —— 那些是汉字的一横、一笔竖撇。
   *   而"用户想画一条直线"是**有意识**的动作，不会只画 40px。
   *   ⚠ 这条闸是**新的**，所以它必须配一个反证（见 [7] 的直线那一例 + 下面那段注释）。 */
  if (raw.length < LINE_MIN_PTS) return null
  const chord = dist(pts[0], pts[pts.length - 1])
  if (chord < LINE_MIN_CHORD) return null
  const line = fitLine(pts)
  if (line && line.score >= MIN_SCORE) return withOffset(line, n)
  return null
}

/* 把归一化时减掉的偏移加回去 —— 判读在原点附近做，返回的结果要在**原来的位置**。
   ⚠ 漏了这一步的后果：规整出来的形状跑到世界坐标原点（左上角那一块），
     屏幕上看起来像"我的东西没了、左上角多了个圆"。 */
function withOffset(s, n) {
  const o = { ...s, ox: n.ox, oy: n.oy }
  if (s.a) o.a = { x: s.a.x + n.ox, y: s.a.y + n.oy }
  if (s.b) o.b = { x: s.b.x + n.ox, y: s.b.y + n.oy }
  if (s.cx != null) {
    o.cx = s.cx + n.ox
    o.cy = s.cy + n.oy
  }
  if (s.box) o.box = { x: s.box.x + n.ox, y: s.box.y + n.oy, w: s.box.w, h: s.box.h }
  return o
}

export function shapeLabel(kind) {
  return kind === 'line' ? '直线'
    : kind === 'rect' ? '矩形'
      : kind === 'triangle' ? '三角形'
        : kind === 'circle' ? '圆'
          : kind === 'ellipse' ? '椭圆' : '形状'
}

// ─────────────────────────────── 拟合（生成规整的笔迹）───────────────────────────────

/* 把认出形状的那一笔**换成规整的一笔**。
 *
 * ★ 接口上它是"points 进、points 出"：调用方拿 `fitShape(s.points, shape)` 的结果
 *   造一条新笔迹（`newStroke`），旧的那条删掉。**不要**在原地改 ——
 *   板的数据是纯的（见 board.js 顶部），而且撤销要能一步退回去。
 * ★ 采样密度：规整后的形状**不需要**那么密的点。
 *   手写的一笔有两三百个点，一个圆用 72 段（5° 一段）已经完全看不出来是折线了。
 *   点少了的好处是文件小、渲染快（而且"规整"这件事本身就该让数据变干净）。
 *   直线就是两点。
 *
 * ★ 压力值：统一给 0.5。
 *   为什么不留原笔的压力：规整之后这一笔的**采样密度变了**，逐点搬压力没有意义
 *   （原来第 37 个点对应现在哪一段？）。而给一个中性的恒定压力，
 *   画出来的粗细均匀 —— 那正是"规整"该有的样子。
 *   ⚠ 如果用户开的是"按压力变粗细"，这条线会是等粗的。这是**有意的**：
 *     把一根忽粗忽细的手抖线"规整"成一条粗细也还在抖的线，反而更像没规整过。
 */
export function fitShape(stroke, shape) {
  if (!shape) return null
  const flat = []
  const push = (x, y) => {
    /* 存盘精度 1/10 像素（和 geometry.js 的 Q 一致）—— 规整出来的坐标本来就是
       算出来的浮点数，不 round 会在文件里留下一串 .123456789。 */
    flat.push(Math.round(x * 10) / 10, Math.round(y * 10) / 10, 0.5)
  }

  if (shape.kind === 'line') {
    push(shape.a.x, shape.a.y)
    push(shape.b.x, shape.b.y)
    return flat
  }

  if (shape.kind === 'circle') {
    const N = 72
    for (let i = 0; i < N; i++) {
      const t = (i / N) * Math.PI * 2
      push(shape.cx + shape.r * Math.cos(t), shape.cy + shape.r * Math.sin(t))
    }
    /* 首尾相接：闭合的一笔要显式重复第一点，不然渲染出来缺一小段
       （canvas 的 stroke() 不会自动闭合路径）。 */
    push(shape.cx + shape.r, shape.cy)
    return flat
  }

  if (shape.kind === 'ellipse') {
    const N = 72
    for (let i = 0; i < N; i++) {
      const t = (i / N) * Math.PI * 2
      push(shape.cx + shape.rx * Math.cos(t), shape.cy + shape.ry * Math.sin(t))
    }
    push(shape.cx + shape.rx, shape.cy)
    return flat
  }

  if (shape.kind === 'rect') {
    const { x, y, w, h } = shape.box
    push(x, y)
    push(x + w, y)
    push(x + w, y + h)
    push(x, y + h)
    push(x, y) // 闭合
    return flat
  }

  if (shape.kind === 'triangle') {
    /* ★ 三角形的三个顶点**从原笔迹里取**，不是从包围盒推。
       理由：包围盒推出来的三个点是一个"固定的"三角形（比如正三角/等腰），
       而用户画的那个三角形长什么样、尖在哪，只有他自己的笔知道。
       直接用判读时找到的那三个角（fitCorners 给出的点下标）——
       那是**尊重原笔**的做法：规整的是"边直不直、角清不清楚"，
       不是"换成我认定的那个三角形"。
       ⚠ 之前这里是"从包围盒四角里挑最接近的三个再回头找原笔的点"，绕了两圈；
         fitCorners 已经把角的位置算准了，直接取就行。 */
    const src = toPoints(stroke && stroke.points)
    const f = fitCorners(src, MAX_SEG, true)
    let verts = f && f.corners ? f.corners.map((i) => src[i]).filter(Boolean) : null
    /* ★ 接缝那个角要补回来：它就是笔的起点（pts[0]）。
       不补的话，一个三角形的三个顶点里会缺"首尾相接"那一个 ——
       而那恰恰是用户画三角形时最后收笔的地方，位置是准的。 */
    if (verts && f.seam) verts = [src[0], ...verts]
    if (!verts || verts.length !== 3) {
      /* 挑不出来就退回"按包围盒画一个直角三角形" —— 比什么都不做强，
         但这条分支**不该发生**（判读已经确认有三个角了）。 */
      const b = shape.box
      push(b.x, b.y)
      push(b.x + b.w, b.y + b.h)
      push(b.x, b.y + b.h)
      push(b.x, b.y)
      return flat
    }
    for (const p of verts) push(p.x, p.y)
    push(verts[0].x, verts[0].y) // 闭合
    return flat
  }

  return null
}

function clamp01(x) {
  if (!Number.isFinite(x)) return 0
  return Math.max(0, Math.min(1, x))
}

/* ─────────────────────────── 给界面用的一层 ───────────────────────────
 *
 * 框住一撮笔 → "这里面有哪些笔能被规整"。
 *
 * ★ 它返回**每一笔各认一遍**的结果，让调用方决定（UI 上"框里 3 笔，其中 2 笔可以规整"）。
 *   为什么不在这里合并：合并的规则是**界面**的事（要不要把两条短笔画成一条线？
 *   要不要只规整能认的那几条、剩下原样留着？），而它取决于用户点的是哪个按钮。
 *   这里只回答"这一笔是什么形状"这个纯几何问题。
 */
export function recognizeStrokes(strokes) {
  const out = []
  for (const s of strokes || []) {
    const shape = recognizeShape(s)
    if (shape) out.push({ id: s.id, shape, label: shapeLabel(shape.kind) })
  }
  return out
}

/** 把一撮笔里的**能认的全认了**，返回新的 strokes 数组 + 改了哪些。纯函数。 */
export function regularizeStrokes(strokes) {
  const next = []
  const changed = []
  /* ★ `shapeObjects` 是给"这个图形之后还要能缩放/旋转/重开还在"那一条路用的
     （`shape-object.js`）。它**不是** `changed` 的替代品：
       · `changed` 管"刚才发生了什么"（给提示语、给自检按 kind 数数），
         字段是 `{ id, kind, label }`，而 **kind 是判读层的 five-kind**，
         正圆报的是 `'circle'` 而对象层一律是 `ellipse`（见 shape-object.js 的
         SHAPE_KINDS 那段）。把两者合并，就会有人拿 `changed[i].kind` 当对象层的
         kind 用 —— 那是个**静默**的错（圆的 `rx/ry` 拿不到，手柄画不出来）。
       · `shapeObjects` 管"这一笔现在是什么东西"，字段是 `{ id, shape }`，
         shape 可以直接喂给 `retargetStroke`。
     两个数组**同序**（都是"认出来的那些笔"的顺序），但名字不同、用途不同。 */
  const shapeObjects = []
  for (const s of strokes || []) {
    const shape = recognizeShape(s)
    if (!shape) {
      next.push(s)
      continue
    }
    const obj = recognizeShapeObject(s, shape)
    /* ★★ 规整 = **拿图形对象重烤一遍点**（`retargetStroke`），不是用 `fitShape` 单独算一份。
     *
     * ⚠ 这里踩过一次，代价是"存→读→再存不再逐字节一致"（每次开板留一条假 diff）。
     *   第一版是 `fitShape(s, shape)` 出点、`recognizeShapeObject(s, shape)` 出参数 ——
     *   **同一件事算了两遍**。而这两遍喂的不是同一组数：
     *     · `fitShape` 用的是**判读层的原始参数**（比如半径 80.08663260372299）；
     *     · 存进文件的是**规范化之后的参数**（80.1，1/10 像素）。
     *   于是盘上那份点的第 30 行是 478.4，而按盘上的参数重烤出来是 478.5 ——
     *   读盘那一步（`normalizeStroke` 按 shape 重烤）把点改了 **0.1px**，
     *   于是"存→读→再存"就有了一处不同。屏幕上那一丁点看不出来，**只有字节能抓住它**。
     *   ⇒ 修法：**点永远从规范化之后的参数烤**（`retargetStroke` 内部就干这个），
     *     而规范化之后的参数就是进文件的那一份。一份参数、一条路。
     *     `fitShape` 仍然导出、也仍然有自检（[7] 那一节直接验它）——
     *     它是"给点不给参数"的调用方用的那个入口，只是**规整这条路不再用它**。 */
    const baked = obj ? retargetStroke(s, obj) : null
    if (!baked || !baked.shape || !baked.points || baked.points.length < 6) {
      next.push(s)
      continue
    }
    /* ★ 新笔迹保留旧笔的 id。
       ⚠ 这一点和"粘贴"那族**正好相反**（那里必须发新 id，因为可能撞上目标板上已有的）。
         这里是在**同一张板上替换**同一笔：沿用 id 有三个好处 ——
         ① 板框的成员（存的是 id）不会因为规整一下就把这一笔踢出去；
         ② 连接上挂的 cond / link 字段跟着这一笔走（它们住在这条 stroke 上）；
         ③ 撤销/重做就是一次普通的数据替换，不用处理"id 换人了"。
       ★ 被保留的字段：tool / color / width / pressure / link / cond —— 只换 points。
         颜色和粗细是用户选的，规整形状**不该**把它们一并改掉。
       ★ 写进去的 `shape` 字段（"这一笔是个什么图形"）见 shape-object.js：
         它让图形重开之后还记得自己是个图形（手柄、缩放、旋转都跟着回来）。 */
    next.push(baked)
    changed.push({ id: s.id, kind: shape.kind, label: shapeLabel(shape.kind) })
    shapeObjects.push({ id: s.id, shape: baked.shape })
  }
  return { strokes: next, changed, shapeObjects }
}

/* ── 判读结果 → **可以缩放/旋转的图形对象**（`shape-object.js` 的 `shapeFromRecognized`）──
 *
 * ★ 为什么不直接在 `recognizeShape` 的返回值上补一个 `verts` 完事：
 *   因为**三角形的顶点不在判读结果里**。`fitTriangle` 只给包围盒和三个角的下标，
 *   真正的三个顶点是 `fitShape` 现场从原笔迹里取的（见它那段"尊重原笔"）。
 *   于是"对象层拿到的那三个顶点"和"屏幕上画出来的那三个顶点"必须来自**同一处**，
 *   否则拖一下手柄，图形会跳到另一个位置上（两套顶点，必然差一次更新）。
 *   ⇒ 这一个函数就是那一处：它把 `fitShape` 用的那份顶点**再算一遍、交给调用方**
 *     （`fitShape` 内部也算一遍，但那一次的结果已经变成点了 —— 这里要的是参数）。
 *   ⚠ 两次计算的结果**必然相同**：同一份 `pts`、同一个 `MAX_SEG` / `true`、
 *     同一个 `src[0]` 补缝逻辑。改这里任何一条时，`fitShape` 里那一段必须一起看。
 *
 * ★ 认不出的形状或取不到参数 → **返回 null**（那一笔就只是一条普通笔迹，
 *   不带 `shape` 字段、没有手柄）。宁可少一个手柄，也不许造一个"和屏幕上那一笔
 *   长得不一样"的对象 —— 那会让用户一拖手柄图形就跳。 */
export function recognizeShapeObject(stroke, recog) {
  const r = recog || recognizeShape(stroke)
  if (!r) return null
  if (r.kind === 'triangle') {
    const src = toPoints(stroke && stroke.points)
    const f = fitCorners(src, MAX_SEG, true)
    let verts = f && f.corners ? f.corners.map((i) => src[i]).filter(Boolean) : null
    if (verts && f.seam) verts = [src[0], ...verts]
    if (!verts || verts.length !== 3) verts = null
    return shapeFromRecognized({ ...r, verts })
  }
  return shapeFromRecognized(r)
}
