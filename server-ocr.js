/* 这一次调用**花了多少** —— 一处读出来，别处不许再解析 upstream 的 usage 形状。
 *
 * 为什么要它（2026-09-22 加的）：在这之前整个仓库**一次都没读过 `usage`** ——
 * 「这一趟花了多少、缓存命中多少」全靠猜。而实测出来的事实是：钱几乎全在 thinking 上
 * （同一页 thinking 916~3219 token、占输出的 69%~89%），输入那一侧便宜到可以忽略。
 * 没有这个数，以后任何"改一改是不是更省了"都只能靠感觉。
 *
 * ⚠ 上游的字段名有两套（都实测见过）：`prompt_cache_hit_tokens` / `prompt_cache_miss_tokens`
 *   是顶层那对；`prompt_tokens_details.cached_tokens` / `completion_tokens_details.reasoning_tokens`
 *   是嵌在 details 里的那对。两个都读，读不到就退回自己算（prompt - hit）。
 * ⚠ 读不出来（老服务、别的 provider）**返回 null**，不是一堆 0 —— 界面上"没有这个数"
 *   和"这个数是 0"是两句不同的话。 */
export function usageOf(u) {
  if (!u || typeof u !== 'object') return null
  const n = (v) => (Number.isFinite(Number(v)) ? Number(v) : 0)
  const details = u.prompt_tokens_details && typeof u.prompt_tokens_details === 'object' ? u.prompt_tokens_details : {}
  const cd = u.completion_tokens_details && typeof u.completion_tokens_details === 'object' ? u.completion_tokens_details : {}
  const prompt = n(u.prompt_tokens)
  const hit = u.prompt_cache_hit_tokens != null ? n(u.prompt_cache_hit_tokens) : n(details.cached_tokens)
  const miss = u.prompt_cache_miss_tokens != null ? n(u.prompt_cache_miss_tokens) : Math.max(0, prompt - hit)
  return {
    prompt,
    completion: n(u.completion_tokens),
    cached: hit,
    miss,
    /* 思维链的 token（**算在 completion 里面**，不是额外的一份） */
    reasoning: n(cd.reasoning_tokens),
    total: n(u.total_tokens) || prompt + n(u.completion_tokens),
  }
}

/* ── DeepSeek：OpenAI 兼容的 /chat/completions ──
   契约（查过官方文档，别凭记忆改）：
     POST https://api.deepseek.com/chat/completions
     Header: Authorization: Bearer <key>
     Body:   { model, messages: [ { role:'user', content: [ {type:'text'}, {type:'image_url', image_url:{url:'data:image/png;base64,…'}} ] } ] }
     返回:   { choices: [ { message: { content: "…", reasoning_content: "…" } } ], usage: {…} }
   图片用 base64 data URL 内联（官方支持的三种方式里最简单的一种，不用先传 Files）。

   ★ 三件实测过、写代码时会踩的事（2026-09-22 量的，探针留在 README 那一节）：
   ① 这个模型**默认开着 thinking，而且默认 effort=high** —— 回包里的 `reasoning_content`
      就是它。思维链按**输出**计价（最贵那档），实测占一次调用输出的 69%~89%。
      要关就发 `thinking: { type: 'disabled' }`（现在**没关**，用户 2026-09-22 定的）。
   ② **thinking 模式下 `temperature` 是无效的** —— 官方原话是"不会报错，但也不起作用"。
      所以下面那个 `temperature` 在开着 thinking 的今天**只是个占位**：哪天换了模型、
      或者关了 thinking，它才真的生效。别把它当成"回答口吻已经调好了"。
   ③ `max_tokens` **把思维链也算在内**（见 `MODE_LIMITS` 那一段）：它是兜底，不是开关。 */
export async function callDeepSeek(cfg, imageBytes, { mode = 'formula', timeoutMs = 30000, input = '', lines = '', page = 0, question = '', history = [], image2 = null, images = [], picked = false, effort = null } = {}) {
  if (!hasKey(cfg)) return { ok: false, kind: 'no-key', error: '还没填密钥' }
  /* 想多深：显式传了就用传的（探针/对比用），否则查 MODE_EFFORT 那张表。
     ★ 表里查不到（新加的 mode 忘了登记）就**不发这个字段** —— 上游默认是 high，
       那是最保守的一档；不写 fallback 成 'low'，"忘了登记"就变成静默降质。 */
  const wantEffort = typeof effort === 'string' ? effort : MODE_EFFORT[mode]
  const wantText = mode === 'text' || mode === 'board' || mode === 'doc'
  /* 九段提示词：认公式 / 认文字 / 按行抄（带行清单）/ 结构整理（纯文本，不看图）/
     课件整理（一页 → 知识点 JSON）/ **整份课件的提纲** + **做题须知**（纯文本、不发图，
     两者共用同一份"逐页摘要"输入）/ **框选追问**（两张图 + 上一轮对话 → 一段回答）/
     **作业辅导**（作业页的图 + 这节课的讲义 → 每道题的答案和解析）/
     **作业追问**（作业页的图 + 刚给出的答案 → 把卡住的那一点讲通）。 */
  const prompt =
    mode === 'structure'
      ? STRUCT_PROMPT
      : mode === 'docsum'
        ? SUMMARY_PROMPT
        : mode === 'rules'
          ? RULES_PROMPT
          : mode === 'doc'
          ? DOC_PROMPT
          : mode === 'ask'
          ? askPrompt(page)
          : mode === 'hwask'
            ? hwaskPrompt()
            /* 速查那一趟（2026-09-28）：提示词是**固定的** —— 它不看页码，也没有要填的
               占位符；要问什么全在 `input` 里（课程 / 整句 / 那个词），由 `lookupInput` 拼。
               ⇒ 这里不必再造一个 `lookupPrompt()` 包一层。 */
            : mode === 'lookup'
              ? LOOKUP_PROMPT
              : mode === 'homework'
                ? /* ★ 两个字段各有各的意思，别读反了：`question` = **学生说的那句话**
                   （"第 12 页第 3 题"，或者圈选题里那句补充说明），
                   `input` = **这节课的讲义**（板上那些讲解卡，
                   由 src/lib/homework.js 的 collectKnowledge 拼出来，可能是空串）；
                   `picked` = 他是**用框圈的题**（那时候两张图的说法是另一套）。 */
                homeworkPrompt(question, input, { picked })
              : mode === 'board'
                ? boardLinesPrompt(lines)
                : wantText
                  ? TEXT_PROMPT
                  : FORMULA_PROMPT
  /* ★ 页码要**写在图上那一段文字里**，不能只放在请求的别处：
     模型看不到我们的字段名，只看得见 content 里那几段。
     课件整理靠它把每条知识点挂到页上（doc-cards.js 的 page），
     所以这一行是那个功能的**契约的一部分**，不是装饰。
     ⚠ 框选追问那一段**不拼这一行**：它的页码已经写进 `ASK_PROMPT` 的开头
       （"他正在看课件第 N 页"），而且那一趟还多两个占位符要填 ——
       两处各拼一遍，一定有一处忘了填。 */
  const promptText = mode === 'doc' && Number(page) > 0 ? prompt + `\n\n这一页是**第 ${Number(page)} 页**。` : prompt
  /* 整板转录用专用档（boardModel），没配就回落到普通模型。
     ⚠ note 里报的是**真用了哪个**——不然"设置里写的 A、实际用的 B"没人看得出来。
     ★ 结构整理那一趟走**普通那档**：它是纯文本、又便宜又快，不值得动 boardModel
       （那是给"看图认一整块板"这种最难的活准备的）。
     ★ 课件整理**也走普通那档**：它一页一次调用（40 页就是 40 次），用大模型的价格
       是做不下去的；真嫌不够好，用户可以在设置里把普通那档换掉。
     ★ 框选追问同理走普通那档：一次追问就是一次调用，而它是"讲一个点"，
       不是"读一整页"——按价钱算它更该用便宜那档。
     ★ 作业辅导也走普通那档：一次就是几页作业 + 一段讲义，和课件整理一个量级。 */
  const usedModel = mode === 'board' && cfg.boardModel ? cfg.boardModel : cfg.model || DEFAULT_CONFIG.model
  /* 结构整理**没有图**：content 就是一段文字（提示词 + 那一份"行清单 + 每行的字"）。
     ★ 课件提纲（docsum）**也走这里**，而且**必须**走这里（见 SUMMARY_PROMPT 那段：
       让它看见图，那道"不许引入新事实"的墙就拆了）。 */
  const imageBlock = (bytes) => ({
    type: 'image_url',
    image_url: { url: 'data:image/png;base64,' + Buffer.from(bytes).toString('base64') },
  })
  /* 这一趟要发哪几张图 —— **归一在一处**。
   * 两条路给的东西不一样：老的那条（框选追问）给 `image` + `image2`（整页 + 裁图），
   * 新的那条（作业辅导）给 `images` 数组（一页一张）。各拼一遍的话，
   * "第二张到底发出去没有"这种事就得看两处 —— 而它正是那条自检要查的东西。 */
  const imgs = (Array.isArray(images) && images.length ? images : [imageBytes, image2]).filter(Boolean)
  /* ⚠⚠ `lookup` **必须在这个组里**（2026-09-28）：它是不带图的纯文本趟。
     漏了的话它会掉到最下面那个分支 —— 把一张根本不存在的图编码成 base64 发出去，
     得到的不是报错，而是"模型看着一张空白图回答问题"（比报错糟得多：它还会一本正经地答）。 */
  const content =
    mode === 'structure' || mode === 'docsum' || mode === 'rules' || mode === 'lookup'
      ? [{ type: 'text', text: prompt + '\n\n' + String(input || '') }]
      : mode === 'homework'
        ? /* ★ 作业辅导：**一页一张图，顺序就是页序**。页码不用写在别处 ——
             每一页的图上方都画着一条白带写着"第 N 页"（前端 homework-images.js 画的），
             提示词第一句就说了"页码写在每张图的上方"。 */
          [{ type: 'text', text: promptText }, ...imgs.map(imageBlock)]
        : mode === 'ask' || mode === 'hwask'
          ? /* ★ 两张图（框选追问）/ 几张作业页（作业追问），顺序**和提示词里说好的**
               一一对应：框选追问第一张整页（带红框）、第二张红框里那一块放大。
               第二张没有（老前端只发了一张）就退回单图 ——
               "上下文少一点"不该让整个问题问不出去。
             ★ 作业追问发的是**第一趟那几张作业页**（一页一张，页码画在图上）——
               老师必须还看得见题，才能讲清"答案里那一步"。 */
            [{ type: 'text', text: promptText }, ...imgs.map(imageBlock)]
          : [{ type: 'text', text: promptText }, imageBlock(imageBytes)]

  /* ★ 多轮（只有框选追问有）：**图和提示词放第一条 user 消息，问答按时间顺序跟在后面，
      这一次问的那句话排在最后**。
   ★★ 拼出来的形状（写下来，免得下次又把它读反 —— 2026-09-22 我自己读反过一次）：
        [0] user      = 两张图 + 那段提示词（**每一轮都一模一样**，不带问题）
        [1..n]        = 上一轮那些轮次，按时间顺序（… 我问的、它答的）
        [n+1] user    = **这一次问的那句话**
      ❌ 从前不是这个形状："这一次问的"拼在**第 0 条**里（提示词的最后一行），
         于是顺序是"新问题 → 上一轮的问 → 上一轮的答"，读起来是倒的；
         更贵的是那两张图**排在分叉点之后**，前缀缓存永远命不中（见 askPrompt 那段）。
      ✅ 现在第 2 轮是第 1 轮**原样接着长**（A+B → A+B+C），
         第 1 轮留下的那个缓存前缀单元被完整匹配 —— 提示词和两张图都按命中价走。
      为什么每一轮还要重发那两张图：这一趟**服务端不留会话状态**，而"接着问"
        必须让模型重新看到那一块东西，否则第二问就成了空口回答；换来的是**没有状态可错**：
        换页、换板、关窗口，都不会留下一个指向别处的会话。
   ★★ 还有一道**必须**做的映射：`parseAskHistory` 交出来的是 `{ role, text }`，
      而上游的契约是 `{ role, content }`。**直接 spread 进去就是一个没有 content 的
      assistant 消息** —— 上游不报错（那一条被当成空消息），模型看到的是
      "自己刚才什么都没说"。2026-09-22 就是在这里栽的：那一条自检断言
      （"上一轮的回答在历史里"）绿的，因为它查的是我们的 `text` 字段。
      映射写在这里、一处。
   ★ **作业追问（hwask）走的是同一形状**（见 HWASK_PROMPT 那段）：第 0 条一样、
     历史一样、最后一条是这一次问的。差异只在提示词和发哪几张图。
     ⚠ 别把 `question` 拼进第 0 条 —— 那正是把前缀缓存打断的那个写法。 */
  const messages =
    mode === 'ask' || mode === 'hwask'
      ? [
          { role: 'user', content },
          ...history.map((h) => ({ role: h.role, content: h.text })),
          { role: 'user', content: mode === 'hwask' ? hwaskQuestion(question) : askQuestion(question) },
        ]
      : [{ role: 'user', content }]

  const body = JSON.stringify({
    model: usedModel,
    // temperature 0：识别是"抄"不是"创作"，让它尽量别发挥。
    // ★ 框选追问**不跟这一条**：它要的是"讲明白"，措辞上允许它说人话
    //   （0 会让回答变成教科书腔，而那正是用户抱怨"读完还是不懂"的原因之一）。
    // ★ 作业辅导同理要 0.3：它的解析也必须是"人话"，0 会把它写成教辅书的标准答案腔。
    // ★ 作业追问（hwask）也走 0.3：它就是"接着讲人话"，和框选追问同一个理由。
    // ★ 课件整理（doc）**也走 0.3**（2026-09-23）：它要的是"老师课上会说的那几句"，
    //   而 0 会把它压成教辅书的标准答案腔 —— 那正是用户抱怨过的地方。
    // ⚠⚠ 这几个数**只在 thinking 关掉的那些趟上生效**（`MODE_EFFORT` 里标 `'off'` 的）：
    //   模型开着 thinking 时，`temperature` 被上游忽略（官方原话："不会报错，但也不起作用"）。
    //   2026-09-23 之前它是整片失效的（十趟全开着 thinking）；现在 formula/text/board/doc
    //   关掉了 thinking ⇒ **这四个数开始真的起作用了**。
    //   ⇒ 反过来也成立：把某一趟从 `'off'` 改回 `high`，它的 temperature 会**重新失效** ——
    //     那时候"改了温度没变化"不是 bug，是上面这句话。
    /* ★ 速查（lookup）**必须**在 0.3 这一组里（2026-09-28）：它 thinking 是 `'off'`
       （理由见 MODE_EFFORT 那一格），所以 temperature 对它**真的起作用** ——
       落到默认的 0 上，一句大白话会被压成词典条目，而那恰恰是"看完还是不懂"的那副腔。 */
    temperature:
      mode === 'ask' || mode === 'homework' || mode === 'hwask' || mode === 'doc' || mode === 'lookup' ? 0.3 : 0,
    /* 输出上限：**只是跑飞兜底**，不是省钱开关（它把 thinking 也算在内，
       设小了会把答案整个掐掉 —— 见 MODE_LIMITS 那一段的实测）。 */
    max_tokens: MODE_LIMITS[mode] || MODE_LIMITS.formula,
    /* 想多深（见 MODE_EFFORT 那一段）。只在这一趟**有登记**时才发 ——
       没登记就不发这个字段，交给上游自己的默认（high，最保守那档）。
       · `'off'` = 整个关掉思维链；· 其余（`low` / `medium` / `high`）= 少想/多想一会儿，
         答案照样完整。⚠ 关掉之后 `temperature` 会开始生效（见 MODE_EFFORT 那段）。 */
    ...(wantEffort === 'off'
      ? { thinking: { type: 'disabled' } }
      : wantEffort
        ? { reasoning_effort: wantEffort }
        : {}),
    messages,
  })

  let res
  try {
    res = await httpRequest(cfg.dsBase, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + cfg.token },
      body: Buffer.from(body, 'utf8'),
      timeoutMs,
    })
  } catch (e) {
    return netError(e, timeoutMs)
  }
  if (res.status < 200 || res.status >= 300) return classifyHttp(res.status, res.text)

  let parsed = null
  try {
    parsed = JSON.parse(res.text)
  } catch {
    return { ok: false, kind: 'bad', error: '识别服务回的不是 JSON', raw: res.text.slice(0, 300) }
  }
  const replyText =
    (parsed.choices && parsed.choices[0] && parsed.choices[0].message && parsed.choices[0].message.content) || ''
  /* 这一趟花了多少（每次调用一份）。读不出来就是 null —— 见 usageOf 那一段。 */
  const usage = usageOf(parsed.usage)

  if (mode === 'structure' || mode === 'docsum' || mode === 'rules') {
    /* 纯文本那几趟：回的就是那段 JSON。**这一层不解析它** —— 落行校验是纯函数
       （src/lib/board-structure.js）、提纲那一份是 src/lib/doc-summary.js 的
       normalizeSummary、须知那一份是同文件的 normalizeRules，都在自检里断言得住；
       这里解析等于把同一份规矩写两遍。
       ★ 剥 ``` 围栏：模型回 JSON 时老爱包一层（`stripFence` 只剥**整段**包着的，
         正文里出现围栏是内容的一部分）。那两份 normalize 自己也剥一次 ——
         两道都留着不是冗余：这一道让服务端的日志和 debug 里看到的是干净 JSON。 */
    const text = stripFence(replyText)
    if (!text) {
      const what =
        mode === 'docsum'
          ? '课件提纲没回内容（它可能觉得这份内容没什么可整理的）'
          : mode === 'rules'
            ? '做题须知没回内容（它可能觉得这份内容里没什么规矩可讲）'
            : '结构整理没回内容（多半是它把话说完了就停）'
      return { ok: false, kind: 'empty', error: what, raw: '' }
    }
    const note = (mode === 'docsum' ? '课件提纲来自 ' : mode === 'rules' ? '做题须知来自 ' : '结构整理来自 ') + usedModel
    return { ok: true, text, conf: null, note, usage }
  }

  if (mode === 'ask' || mode === 'hwask') {
    /* 框选追问 / 作业追问那一趟：回的**就是一段人话**（可能夹着 `$…$` 式子）。
       这里只做一件事：剥掉整段外面的 ``` 围栏 —— 那一段人话要按 Markdown 排进
       小窗（rich.js 的 richHtml），包着围栏的话整段会变成一坨原样文字。
       ⚠ **不做别的清洗**：这是唯一一趟"模型自由说话"的调用，任何"抠一行""取冒号后面"
         的处理都会把学生的答案砍掉半句（`cleanModelOutput` 那一族的账见它的注释）。 */
    const text = stripFence(replyText)
    if (!text) {
      const what = mode === 'hwask' ? '模型没回内容（它可能觉得这一点没什么可讲的）' : '模型没回内容（它可能以为这一块没什么可讲的）'
      return { ok: false, kind: 'empty', error: what, raw: String(replyText).slice(0, 200) }
    }
    const note = (mode === 'hwask' ? '作业追问来自 ' : '回答来自 ') + usedModel
    return { ok: true, text, conf: null, note, usage }
  }

  if (mode === 'lookup') {
    /* 速查那一趟（2026-09-28）：回的**就是那四行带标签的字**（词 / 讲 / 例 / 近）。
       这里只做一件事：剥掉整段外面的 ``` 围栏（模型老爱包）。
       ★ **不按冒号切、不补齐缺的行**：把文本拆成四个字段、以及"少了一两行怎么算"
         都在前端的纯函数里（src/lib/lookup.js），那边在自检里断言得住 ——
         在这儿再写一遍等于把同一份规矩写上两处（doc / homework 同一条纪律）。
       ⚠ 别让它落到下面 `wantText` 那一条路上：`cleanTextOutput` 会把引号和空行剥掉，
         而这趟的行本身就可能带着引号（式子、书名）。 */
    const text = stripFence(replyText)
    if (!text) {
      return { ok: false, kind: 'empty', error: '模型没回内容（这个词它可能也不认识）', raw: String(replyText).slice(0, 200) }
    }
    return { ok: true, text, conf: null, note: '速查来自 ' + usedModel, usage }
  }

  if (mode === 'homework') {
    /* 作业辅导那一趟：回的是一段**JSON**（`{ problems: [...] }`）。
       这里只做一件事：剥掉整段外面的 ``` 围栏（模型老爱包）。
       ★ **不解析、不清洗**：分题、字段校验、空壳丢掉都在纯函数里
         （src/lib/homework.js 的 parseHomework），那边在自检里断言得住 ——
         在这儿再解析一遍等于把同一份规矩写两处（doc 那一路同一条纪律）。
       ⚠ 千万**别**让它走 `cleanTextOutput`：那一趟会剥引号、认 EMPTY 哨兵，
         而 homework 的正文里到处是引号（字符串字段）—— 剥一下 JSON 就废了。 */
    const text = stripFence(replyText)
    if (!text) {
      return { ok: false, kind: 'empty', error: '模型没回内容（它可能以为这几道题没什么可讲的）', raw: String(replyText).slice(0, 200) }
    }
    return { ok: true, text, conf: null, note: '作业辅导来自 ' + usedModel, usage }
  }

  if (wantText) {
    /* ⚠ **按行抄这一趟不能走 `cleanTextOutput` 之外的处理**：`L<行号>|` 前缀是契约的一部分，
       剥引号/围栏那两步保留（模型老爱加），但**一行都不能删**（它是行号的载体）。
       ★ 课件整理（doc）走的就是这条路：它回的也是一段**行不能删**的 JSON
         （压行 = JSON 里少几个逗号，整批白读）。解析在校验那一侧（doc-cards.js
         的 parseDocExtract）—— 这里解析等于把同一份规矩写两遍。 */
    const text = cleanTextOutput(replyText)
    if (!text) {
      return { ok: false, kind: 'empty', error: '模型没认出文字（它回的是一句解释，不是一个词）', raw: String(replyText).slice(0, 200) }
    }
    const what = mode === 'board' ? '整板转录' : mode === 'doc' ? '课件整理' : '识别'
    /* ⚠⚠ 加一趟新的"回文字"的 mode 就得回这儿加一行 —— **漏了不会报错**：
       它会静默地落到最后那个 `'识别'` 上，日志里显示成"手写识别认出：
       {...一份提纲的 JSON...}"（2026-09-22 加 hwask 时踩过一次，
       自检里有一条判据专门盯这行。见 scripts/check-homework.js 第 ⑨ 节）。 */
    return { ok: true, text, conf: null, note: what + '来自 ' + usedModel, usage }
  }

  const latex = cleanModelOutput(replyText)
  if (!latex) return { ok: false, kind: 'empty', error: '模型没认出公式（它回的是一句解释，不是式子）', raw: String(content).slice(0, 200) }
  return { ok: true, latex, conf: null, note: '识别来自 ' + usedModel, usage }
}

/* 整段被一对 ``` 包着就把它剥掉（模型的习惯），别的一个字不动。
 * ★ 为什么要单独一个（不复用 cleanModelOutput）：那个函数会"抠出最像 LaTeX 的那一行"、
 *   "取最后一个冒号后面那段" —— 对**一段回答**是灾难（学生的问题答案里到处是冒号和
 *   换行，抠一下就把答案砍成半句）。这里只做"剥壳"这一件事。
 * ⚠ 只剥**整段**包着的：正文里出现代码围栏（模型偶尔写）是内容的一部分，
 *   不能连它一起剥。 */
export function stripFence(raw) {
  const s = String(raw == null ? '' : raw).trim()
  const m = /^```[a-zA-Z]*\s*\n([\s\S]*?)\n?```$/.exec(s)
  return (m ? m[1] : s).trim()
}

/* 模型回话里把公式抠出来。
   ★ 这一段决定了"能不能用"：LLM 会做这些事，全都得处理 ——
     · 包在 ```latex … ``` 里（哪怕你明确说了不要）
     · 前面加一句"图片里的公式是："
     · 带 $ $ 或 \[ \]
     · 干脆回一句"这张图里没有公式"
   处理原则：**能抠出来就抠，抠不出来就老实说没认出**，
   绝不把一整句中文当 LaTeX 塞给卡片（那会渲染成一堆红字，比空着更糟）。 */
export function cleanModelOutput(raw) {
  let s = String(raw == null ? '' : raw).trim()
  if (!s) return ''

  // ① ```latex … ``` / ``` … ```（你说了不要，它还是会包）
  const fence = /```(?:latex|tex|math)?\s*([\s\S]*?)```/i.exec(s)
  if (fence) s = fence[1].trim()

  /* ② 多行就取**含有 LaTeX 特征的那一行**。
     LLM 常见的回法是先一句"图片里是"，再单独一行给公式。 */
  const lines = s.split('\n').map((x) => x.trim()).filter(Boolean)
  if (lines.length > 1) {
    const best = lines.filter(looksLikeLatex).pop()
    if (best) s = best
  }

  /* ③ 一句话里混着"前言 + 公式"：取最后一个冒号后面那段。
     `图片里的公式是：\oint…` → `\oint…`
     `公式：B=\frac…`        → `B=\frac…`
     这一步和上面那条的区别是：**同一行内的前言**，多行那条管不到。
     冒号全是中文全角的话（比如"以下是公式："）也一并处理。 */
  const colon = /[:：]/.exec(s)
  if (colon) {
    const tail = s.slice(colon.index + 1).trim()
    const head = s.slice(0, colon.index)
    // 只在"冒号前像人话、冒号后有东西"的时候才切
    if (tail && !looksLikeLatex(head) && /[\u4e00-\u9fff a-zA-Z]/.test(head)) s = tail
  }

  s = cleanLatex(s)

  // ④ 模型说"没有公式"的各种说法
  if (/^(EMPTY|N\/A|无|没有公式|图片中没有公式|这张图.*没有公式)\.?$/i.test(s)) return ''
  // ⑤ 还是一整句人话：有中文、而且没有任何 LaTeX 特征 → 当没认出。
  //    绝不把中文句子塞进卡片（会渲染成一堆红字，比空着更糟）。
  if (/[\u4e00-\u9fff]/.test(s) && !looksLikeLatex(s)) return ''
  return s
}

/* "这段像不像 LaTeX"。判据故意宽松：宁可多认一个，也别把真公式误判成人话。 */
function looksLikeLatex(t) {
  return /\\[a-zA-Z]|[_^={}]|\d\s*[a-zA-Z]/.test(String(t || ''))
}

/* 模型回话里把**文字**抠出来。
 *
 * ★ 为什么不复用上面那个 cleanModelOutput —— 这是这个功能最容易踩的一脚：
 *   cleanModelOutput 里有一条"一句话里混着前言 + 公式，就取最后一个冒号后面那段"。
 *   对公式是对的（`图片里的公式是：\oint…`），对**文字是灾难**：
 *   笔记里本来就到处是冒号（`安培环路定理：只对稳恒电流成立`），
 *   那一步会把用户写的一整行悄悄砍掉前半句，而**界面上看不出来**
 *   （卡片里就是少了一段字，你会以为是自己没写全）。
 *   所以文字这条路只做三件事，一律"宁可留着，不可删掉"：
 *     ① 剥 ``` 围栏（说了不要它还是会包）
 *     ② 剥掉整段外面被包上的引号（模型爱说"内容是："再配一对引号）
 *     ③ 认 EMPTY 哨兵
 *   多行的取舍也不同：公式取"最像 LaTeX 的那一行"，文字**每一行都留着**。 */
export function cleanTextOutput(raw) {
  let s = String(raw == null ? '' : raw).trim()
  if (!s) return ''

  const fence = /```(?:text|markdown|md|plain|latex|tex)?\s*([\s\S]*?)```/i.exec(s)
  if (fence) s = fence[1].trim()

  // 整段被一对引号包着（半角 / 中文 / 书名号），且里面没有第二对同样的引号
  const pairs = [['"', '"'], ['“', '”'], ["'", "'"], ['「', '」'], ['『', '』']]
  for (const [a, b] of pairs) {
    if (s.length > 1 && s.startsWith(a) && s.endsWith(b) && !s.slice(1, -1).includes(b)) {
      s = s.slice(1, -1).trim()
      break
    }
  }

  /* 句末的句号有半角也**有全角**（"这张图里没有文字。"）。
     这里的 `[.。]?` 不是随手加的：公式那条路漏了全角句号也没暴露 ——
     因为公式的兜底是"有中文且不像 LaTeX 就当没认出"，中文句子照样被丢掉。
     文字这条路的中文是**正文**，兜底那条不存在，所以标点必须自己认全。 */
  if (/^(EMPTY|N\/A|无|没有文字|图片中没有文字|这张图.*没有(文字|内容))[.。]?$/i.test(s)) return ''
  return s
}

/* ── SimpleTex：multipart 直接传图 ──
   契约：POST {base}{|_turbo}，Header 带鉴权，Body 一个 file 字段，
        返回 { status, res: { latex, conf }, request_id }。 */
export async function callSimpleTex(cfg, imageBytes, { timeoutMs = 25000 } = {}) {
  const url = endpointOf(cfg)
  const { body, contentType } = buildMultipart([
    { name: 'file', filename: 'ink.png', type: 'image/png', data: imageBytes },
  ])

  let res
  try {
    res = await httpRequest(url, {
      method: 'POST',
      headers: { ...authHeaders(cfg), 'Content-Type': contentType },
      body,
      timeoutMs,
    })
  } catch (e) {
    return netError(e, timeoutMs)
  }

  if (res.status < 200 || res.status >= 300) return classifyHttp(res.status, res.text)

  let parsedBody = null
  try {
    parsedBody = JSON.parse(res.text)
  } catch {
    /* 不是 JSON —— 按"看不懂"处理 */
  }
  const parsed = parseProviderResponse(parsedBody)
  if (!parsed.ok) return { ...parsed, httpStatus: res.status, raw: res.text.slice(0, 300) }
  return {
    ...parsed,
    httpStatus: res.status,
    requestId: parsedBody && parsedBody.request_id ? parsedBody.request_id : null,
  }
}

function netError(e, timeoutMs) {
  const timedOut = e && /timeout/i.test(e.message || '')
  return {
    ok: false,
    kind: 'network',
    error: timedOut
      ? `识别服务 ${Math.round(timeoutMs / 1000)} 秒没回话（网络慢，或者它那边在排队）`
      : '连不上识别服务：' + ((e && e.message) || e),
  }
}

/* ── 体检：用一张极小的留白图探一下密钥通不通 ──
   为什么不复用用户刚写的那笔：那样"密钥错"和"没写清楚"会混在一起，
   用户不知道该改密钥还是重写。这里发一张留白的图，
   只要鉴权过了就算通（认不出内容是正常的、也是预期的）。 */
export async function testProvider(cfg, { timeoutMs = 20000 } = {}) {
  if (!hasKey(cfg)) return { ok: false, kind: 'no-key', error: '还没填密钥' }
  const png = tinyWhitePng(96, 48)
  const r = await callProvider(cfg, png, { timeoutMs })
  // "没认出东西"恰恰说明鉴权通过了、服务也活着
  if (r.ok) return { ok: true, note: '服务正常，而且从测试图里认出了内容：' + String(r.latex).slice(0, 40) }
  if (r.kind === 'empty') {
    return { ok: true, note: '服务正常（测试图是留白，认不出内容是正常的）' }
  }
  return r
}

/* ── 现场造一张小 PNG（留白）──────────────────────────────────────
   为了一张 96×48 的白图存一个二进制文件进仓库不值得：手写二进制没法在
   diff 里看懂，而"造一张白图"这件事本身就是十几行 zlib 调用。
   PNG 的三块：IHDR（尺寸/位深）、IDAT（压缩过的像素）、IEND。 */
export function tinyWhitePng(w = 96, h = 48) {
  const raw = Buffer.alloc((w * 4 + 1) * h) // 每行前面一个 filter 字节
  for (let y = 0; y < h; y++) {
    const off = y * (w * 4 + 1)
    raw[off] = 0 // filter: none
    for (let x = 0; x < w; x++) {
      const p = off + 1 + x * 4
      raw[p] = 0xff // R
      raw[p + 1] = 0xff // G
      raw[p + 2] = 0xff // B
      raw[p + 3] = 0xff // A
    }
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(w, 0)
  ihdr.writeUInt32BE(h, 4)
  ihdr[8] = 8 // 位深
  ihdr[9] = 6 // 颜色类型：RGBA
  ihdr[10] = 0
  ihdr[11] = 0
  ihdr[12] = 0
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlibDeflate(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ])
}

function chunk(type, data) {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length, 0)
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body) >>> 0, 0)
  return Buffer.concat([len, body, crc])
}

function zlibDeflate(buf) {
  return zlib.deflateSync(buf) // zlib 自带的头（0x78 0x9c）正好是 PNG IDAT 要的
}

/* CRC32（PNG 每块都要）。查表法，表只建一次。 */
let CRC_TABLE = null
function crc32(buf) {
  if (!CRC_TABLE) {
    CRC_TABLE = new Int32Array(256)
    for (let n = 0; n < 256; n++) {
      let c = n
      for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
      CRC_TABLE[n] = c
    }
  }
  let c = 0xffffffff
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}

