/** multipart 里的 `history`（问答小窗的上一轮对话，JSON 字符串）→ 干净的数组。
 *
 * ── 为什么要夹这么紧 ────────────────────────────────────────────────────
 * 这是**唯一一个从浏览器直接进提示词的多轮内容**。不夹的话：
 *   · 一条 10 万字的消息能把一次调用顶爆（而且是花用户的钱）；
 *   · 认不出的 role 直接进 messages 会被上游拒（报错发生在别人家，看不懂）；
 *   · 坏 JSON 混进来会让整个请求 500 —— 而它只是"对话历史"，没有它也该能答。
 * 所以：**认不出的丢掉、超长截断，坏 JSON 当没有**（和缓存那条纪律同源：
 * 辅助的东西坏了不许拖垮主流程）。 */
export function parseAskHistory(raw, { maxTurns = 12, maxChars = 4000 } = {}) {
  let arr = raw
  if (typeof raw === 'string') {
    const s = raw.trim()
    if (!s) return []
    try {
      arr = JSON.parse(s)
    } catch {
      return []
    }
  }
  if (!Array.isArray(arr)) return []
  const out = []
  for (const it of arr.slice(-maxTurns)) {
    if (!it || typeof it !== 'object') continue
    const role = it.role === 'assistant' ? 'assistant' : it.role === 'user' ? 'user' : ''
    const text = typeof it.text === 'string' ? it.text : typeof it.content === 'string' ? it.content : ''
    const t = text.trim()
    if (!role || !t) continue
    out.push({ role, text: t.length > maxChars ? t.slice(0, maxChars) + '…' : t })
  }
  return out
}

