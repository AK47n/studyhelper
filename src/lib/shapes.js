/* 常用形状：把你手画的那一笔认成**规整的**圆 / 椭圆 / 矩形 / 三角形 / 直线，
 * 并生成一条新的笔迹（那条歪的换掉）。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ★★ 先说清它和 ADR-0001 砍掉的"形状判读"是什么关系 —— 这是这个文件最重要的注释。
 *
 * ADR-0001（2026-09-17）删掉了"从形状猜**关系**"那一族：它把汉字折笔的拐角
 * 认成箭头，494/439/620 笔三张真板上被判成箭头的 92 条**没有一条是箭头**，
 * 用户原话「我这里面一个箭头都没有」。那一刀砍得有道理，而且**没有回头**。
 *
 * 但这个文件做的是**另一件事**，而且三处关键差别让"误报"这件事的性质完全不同：
 *
 *   ① **不是猜语义，是画几何。** 那一族猜的是"这两个东西是因果关系"——
 *      一个**看不见的断言**，错了你根本不知道（它默默写进了文件、面板里多一行）。
 *      这里猜的是"这一笔是个圆"—— **结果就摆在你眼前**：你真的看见一个圆。
 *      认错了你一眼就知道，因为屏幕上那个东西的形状不对。
 *
 *   ② **不在你写字的时候动手，只在你说"规整一下"的时候动手。**
 *      那一族是"你每画完一笔它都自动判断"，所以误判的代价摊在**你写的每一个字**上
 *      （这才是误报率 100% 那么要命的原因：它污染的是全部输入）。
 *      这里是框选一块 → 点「◯ 规整」→ 才动手，而且**一步撤销**。
 *      你不点它，笔迹一个字节都不会变。
 *
 *   ③ **有否决权、而且代价对称。** 认不出来就什么都不做（返回 null，按钮都不出现），
 *      认出来但你不同意 → Ctrl+Z，或者干脆用框选里那颗「✕ 删除」。
 *      那一族的否决权（「不算连接」）之所以后来也删掉，正是因为它**没有对象**了。
 *
 * ⚠ **所以有一条铁律：宁可认不出来，也不许认错。**
 *   阈值全部往"保守"那一侧调。认不出来用户只是"没得到帮助"（他继续用手画的）；
 *   认错了是"应用把我画的东西改成了别的" —— 那是对用户笔迹的**侵入**，
 *   而且和那一族不同的是，这一次的错**加上了"是我主动点的"这层难受**。
 *   每一个判据都要能在自检里被一句反证钉住（[6x] 那一节）。
 *
 * ══════════════════════════════════════════════════════════════════════════
 *
 * ── interface ─────────────────────────────────────────────────────────────
 *   recognizeShape(stroke) → null | {
 *     kind: 'line' | 'rect' | 'triangle' | 'circle' | 'ellipse',
 *     label,                 // 给界面用的人话（"直线" / "圆" / …）
 *     score,                 // 0..1，越像越接近 1（界面可以拿它排序/显示"有多像"）
 *     closed,                // 这一笔是不是首尾相接
 *     ...各自的几何          // 详见下面每个 fit 函数的注释
 *   }
 *   fitShape(stroke, shape) → 新的 points（扁平数组）；shape 来自上面（不重新判读）
 *   shapeLabel(kind) → 人话
 *
 * 纯函数，不碰 DOM、不碰 React、不读时间。
 * 点只有一种格式（见 geometry.js）：读进来一律走 `toPoints`。
 */

import { toFlat, toPoints } from './geometry.js'
